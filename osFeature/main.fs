/** OpenRocket-to-Onshape entry point: one sketch per component, then a solid each.
 *  Every *why* is in the numbered notes at the foot of this file. */

// TEMPORARY: reports components that produce no bodies; set false to silence.
const DEBUG_ASSEMBLY = true;

// Payload schema this feature understands; kept in step with parser.ts (note 18).
const EXPECTED_SCHEMA_VERSION = "1.2";

// Where the .ork -> JSON converter lives: the static web app in this repository,
// deployed by .github/workflows/deploy-pages.yml.  Shown in the feature dialog so
// it is one click from the JSON field it produces.
const WEBAPP_URL = "https://ncsu-high-powered-rocketry-club.github.io/openrocket-onshape/";

const FRONT_SKETCH_PLANE = transformRot(rotationMatrix3dEulerXYZ(vector(90, 0, 0) * degree));

annotation {
    "Feature Type Name" : "OpenRocket to Onshape",
    "Editing Logic Function" : "oroEditingLogic",
    "Feature Type Description" : "Constructs a rocket model from a JSON file exported by the OpenRocket-to-Onshape web app. Import the .json and reference it in this feature. When creating an assembly, make sure to insert **composite parts** and fasten together the provided mate connectors.",
    "Icon" : icon::BLOB_DATA,
    "Description Image" : image::BLOB_DATA }
export const oroFeature = defineFeature(function(context is Context, id is Id, definition is map)
    precondition
    {

        annotation { "Name" : "ORO json" }
        definition.orkJsonFile is JSONData;

        // Real PARAMETERS, not locals: a precondition is analysed, never executed,
        // so an `if` there may only test a parameter id (note 24).
        annotation { "Name" : "Motor mass in file",
                    "UIHint" : UIHint.ALWAYS_HIDDEN }
        definition.motorMassInFile is boolean;

        annotation { "Name" : "Motor length in file",
                    "UIHint" : UIHint.ALWAYS_HIDDEN }
        definition.motorLengthInFile is boolean;

        if (!definition.motorMassInFile)
        {
            // Mass is the one motor dimension the file cannot supply (note 16).
            annotation { "Name" : "Motor mass (g)",
                        "Description" : "Mass of the motor in each motor mount, in grams. Leave at 0 to leave the motor's mass unset." }
            isReal(definition.motorMass, MOTOR_MASS_BOUNDS);
        }

        if (!definition.motorLengthInFile)
        {
            // Length is in the file, so this is an override; a LENGTH field (note 16).
            annotation { "Name" : "Motor length",
                        "Description" : "Overrides the motor length from the .ork file. Leave at 0 to use the length of the motor the file selects." }
            isLength(definition.motorLength, NONNEGATIVE_ZERO_DEFAULT_LENGTH_BOUNDS);
        }

        // The converter the JSON comes from, last in the dialog: shown read-only
        // so it is one click to find, and cannot be edited into a link that does
        // not exist.
        annotation { "Name" : "Web app",
                    "Description" : "Open the converter in a new tab to turn an .ork file into the JSON this feature reads.",
                    "Default" : WEBAPP_URL,
                    "UIHint" : [UIHint.READ_ONLY] }
        definition.webAppUrl is string;
    }
    {
        const jsonFile = definition.orkJsonFile;
        if (jsonFile == undefined)
        {
            throw regenError("Select a json file generated by openrocket-onshape");
        }
        const jsonData = jsonFile.jsonData;
        const rocketData = jsonData.rocket;
        const units = rocketData.unitSystem != 'SI' ? inch : meter;
        const topComponents = rocketData.components;

        // A stale payload is caught here, not later as a confusing revolve error.
        const payloadSchema = jsonData.schemaVersion;
        if (payloadSchema != EXPECTED_SCHEMA_VERSION)
        {
            // @keep: a stale payload is the user's problem to fix, not debug noise.
            println("[schema] payload is " ~ toString(payloadSchema) ~ ", this feature needs "
                    ~ EXPECTED_SCHEMA_VERSION ~ " — re-export the JSON from the web app"
                    ~ " (an older file has no innerProfile and cannot be drawn).");
        }

        createComponents(context, topComponents, {
            "transform" : toWorld(WORLD_COORD_SYSTEM),
            "length" : 0 * meter,
            "centerOfPressure" : rocketData.centerOfPressure,
            "bodyTubeRadius" : maxBodyTubeRadius(rocketData.components)
        }, id, units, 0, readMotorOptions(definition));
    });

/** Editing logic: fill the two "in file" flags from the attached payload, which is
 *  where the JSON is really read (notes 24, 26). */
export function oroEditingLogic(context is Context, id is Id, oldDefinition is map, definition is map) returns map
{
    // No JSON yet, or none with a rocket in it, means nothing is known: report
    // "not in file" so both fields are offered, as readMotorOptions would anyway.
    var massInFile = false;
    var lengthInFile = false;

    const jsonFile = definition["orkJsonFile"];
    if (jsonFile != undefined && jsonFile.jsonData != undefined && jsonFile.jsonData.rocket != undefined)
    {
        const payloadComponents = jsonFile.jsonData.rocket.components;
        massInFile = jsonHasMotorMass(payloadComponents);
        lengthInFile = jsonHasMotorLength(payloadComponents);
    }

    definition["motorMassInFile"] = massInFile;
    definition["motorLengthInFile"] = lengthInFile;

    return definition;
}

/** The motor overrides as a map: a mass in grams and an override length (note 21). */
function readMotorOptions(definition is map) returns map
{
    const massGrams = definition.motorMass == undefined ? 0 : definition.motorMass;
    const overrideLength = definition.motorLength == undefined ? 0 * meter : definition.motorLength;

    return {
                "massGrams" : massGrams,
                "overrideLength" : overrideLength
            };
}

/** Does ANY motor mount in the payload carry a real motor length? */
function jsonHasMotorLength(components is array) returns boolean
{
    return jsonMotorFieldPresent(components, "length");
}

/** Does ANY motor mount in the payload carry a motor MASS?  False for every file
 *  today, and a lookup rather than a `false` on purpose (note 27). */
function jsonHasMotorMass(components is array) returns boolean
{
    return jsonMotorFieldPresent(components, "mass");
}

/** Is `field` set to something usable on ANY motor mount, at any depth? */
function jsonMotorFieldPresent(components is array, field is string) returns boolean
{
    if (components == undefined)
    {
        return false;
    }

    for (var comp in components)
    {
        const params = comp.params;
        if (params != undefined && params.isMotorMount == true && params.motorMount != undefined)
        {
            const value = params.motorMount[field];
            if (value != undefined && value > 0)
            {
                return true;
            }
        }

        // Children are searched too: a booster's motor lives several levels down.
        if (jsonMotorFieldPresent(comp.children, field))
        {
            return true;
        }
    }
    return false;
}

// Motor mass bounds: 0 .. 1000 g, DEFAULTING TO 0 so blank means "unset" (note 22).
const MOTOR_MASS_BOUNDS =
{
    (unitless) : [0, 0, 1000]
} as RealBoundSpec;

/** Maximum body-tube radius in the rocket; fins do not affect the CP marker size. */
function maxBodyTubeRadius(components is array) returns number
{
    var maxRadius = 0;
    for (var comp in components)
    {
        if (comp['type'] == 'bodytube' && comp.params.outerRadius != undefined)
        {
            maxRadius = max(maxRadius, comp.params.outerRadius);
        }
        maxRadius = max(maxRadius, maxBodyTubeRadius(comp.children));
    }
    return maxRadius;
}

function createComponents(context is Context, components is array, parentInfo is map, id is Id, units is ValueWithUnits, depth is number, motorOptions is map)
{
    const numComponents = size(components);

    const parentTransform = parentInfo.transform;

    // The PARENT's own sketch, captured before the second loop rebinds it (note 17).
    const parentOwnSketch = parentInfo.parentSketch;

    var lastTform = parentTransform;
    var componentQueryArray = [];

    var componentFaces = makeArray(numComponents);

    // Per-component sketch references; the parent sketch for this component's children.
    var componentSketches = makeArray(numComponents);

    var childrenCalls = makeArray(numComponents);

    for (var i, comp in components)
    {
        if (comp.id == "")
        {
            comp.id = depth ~ "_" ~ i;
        }

        const compId = id + comp.id;
        const sketchId = compId + "compSketch";

        const componentType = comp['type'];
        const length = determineComponentLength(comp) * units;

        const resolvedTransform = resolveTransform(comp.position, units, lastTform, parentTransform, length, parentInfo.length);
        const tform = resolvedTransform[0];
        const topPosition = tform.translation;
        lastTform = resolvedTransform[1];
        const lastPosition = lastTform.translation;

        if (componentType != 'stage' && componentType != 'podset' && componentType != 'parallelstage')
        {
            const sketchPlane = plane(transformToCoordSystem(tform * FRONT_SKETCH_PLANE));
            const compSketch = newSketchOnPlane(context, sketchId, {
                        "sketchPlane" : sketchPlane
                    });

            componentSketches[i] = {
                    "sketch" : compSketch,
                    "sketchId" : sketchId,
                    "plane" : sketchPlane
                };

            sketchComponent(context, comp, compSketch, units, sketchPlane, parentInfo.parentSketch, parentInfo.parentSiblingSketches);

            skSolve(compSketch);

            const sketchFaces = evaluateQuery(context, qSketchRegion(sketchId));
            const faceCount = size(sketchFaces);

            // TEMPORARY diagnostic, terse because the notices pane truncates (note 13).
            if (DEBUG_ASSEMBLY)
            {
                println("  [face] " ~ comp.name ~ " faces=" ~ toString(faceCount));
            }

            // No region: leave the face undefined rather than `continue` (note 4).
            if (faceCount > 0)
            {
                componentFaces[i] = sketchFaces[0];
            }
        }

        childrenCalls[i] = {
                "component" : comp,
                "parentInfo" : {
                    "transform" : tform,
                    "length" : length,
                    "centerOfPressure" : parentInfo.centerOfPressure,
                    "bodyTubeRadius" : parentInfo.bodyTubeRadius,
                    // Set once at depth 0, then INHERITED; recomputing it per level
                    // drops the marker entirely (note 8).
                    "isFirstTopComponent" : parentInfo.isFirstTopComponent == true || (depth == 0 && i == 0),
                    // A FRESH array per component, so the original instances collected
                    // below it belong to this subtree alone (note 34).
                    "assemblyOriginals" : []
                },
                "topPosition" : topPosition,
                "lastPosition" : lastPosition
            };
    }

    for (var i, callInfo in childrenCalls)
    {
        if (callInfo == undefined)
            continue;
        const comp = callInfo.component;
        const compId = id + (comp.id ~ "child");
        var parentInfo = callInfo.parentInfo;
        const tform = parentInfo.transform;
        const topPosition = callInfo.topPosition;
        const lastPosition = callInfo.lastPosition;

        // The parent's sketch plus its siblings, for a root that outruns it (note 1).
        parentInfo.parentSketch = componentSketches[i];
        var parentSiblingSketches = [];
        for (var j, siblingSketch in componentSketches)
        {
            if (j != i && siblingSketch != undefined)
            {
                parentSiblingSketches = append(parentSiblingSketches, siblingSketch);
            }
        }
        parentInfo.parentSiblingSketches = parentSiblingSketches;

        const childrenQuery = qEntityFilter(createComponents(context, comp.children, parentInfo, compId, units, depth + 1, motorOptions), EntityType.BODY);
        const children = evaluateQuery(context, childrenQuery);

        const face = componentFaces[i];

        const bodies = completeComponent(context, comp, face, tform, compId + "complete", units, makeRobustQuery(context, childrenQuery), depth, parentOwnSketch, motorOptions);

        const bodiesCount = bodies == undefined ? 0 : evaluateQueryCount(context, bodies);

        // Mate each component to its neighbour, fore and aft; owner falls back to
        // the children, which is what a stage needs mated (note 20).
        var mateOwner = bodies;
        if (bodiesCount == 0 && evaluateQueryCount(context, childrenQuery) != 0)
        {
            mateOwner = makeRobustQuery(context, childrenQuery);
        }

        // Only the two outermost levels, and never at an end with nothing to mate.
        if (depth <= 1 && evaluateQueryCount(context, mateOwner) != 0)
        {
            if (i != 0)
            {
                opMateConnector(context, compId + "topMateCoord", {
                            "coordSystem" : coordSystem(topPosition, vector(1, 0, 0), vector(0, 0, 1)),
                            "owner" : mateOwner
                        });
            }

            if (i != numComponents - 1)
            {
                opMateConnector(context, compId + "bottomMateCoord", {
                            "coordSystem" : coordSystem(lastPosition, vector(1, 0, 0), vector(0, 0, 1)),
                            "owner" : mateOwner
                        });
            }
        }

        if (bodiesCount == 0)
        {
            if (DEBUG_ASSEMBLY)
            {
                println("  [asm] " ~ comp.name ~ " (" ~ comp['type'] ~ ") produced NO body (face="
                        ~ toString(face != undefined) ~ ", children=" ~ toString(size(children)) ~ ")");
            }
            continue;
        }

        // An assembly's bodies are its children; do not rename/recolour them (notes 3).
        if (!isAssembly(comp['type']))
        {
            setProperty(context, {
                        "entities" : bodies,
                        "propertyType" : PropertyType.NAME,
                        "value" : comp.name
                    });

            const compColor = comp.color;
            if (compColor != undefined)
            {

                setProperty(context, {
                            "entities" : bodies,
                            "propertyType" : PropertyType.APPEARANCE,
                            "value" : color(compColor.red, compColor.green, compColor.blue, compColor.alpha)
                        });
            }

            const material = resolveMaterial(comp.material);

            if (material != undefined)
            {
                setProperty(context, {
                            "entities" : bodies,
                            "propertyType" : PropertyType.MATERIAL,
                            "value" : material
                        });
            }
        }

        // The motor is INSIDE `bodies`, so the NAME set just above landed on it too.
        // Re-assert the motor's own name and colour (note 16).
        restyleMotor(context, compId + "complete", comp, motorOptions);

        componentQueryArray = append(componentQueryArray, bodies);

        // `bodies` is the component's OWN geometry, so a child's bodies are not in
        // it.  Re-read after the pattern, which CONSUMES what it copies (note 25).
        if (!isAssembly(comp['type']) && evaluateQueryCount(context, childrenQuery) != 0)
        {
            componentQueryArray = append(componentQueryArray, makeRobustQuery(context, childrenQuery));
        }

        // A patterned assembly's ORIGINAL instance is `children`; it goes in the
        // accumulator, never the return value, which is a pattern source (note 34).
        if (isAssembly(comp['type']) && effectiveInstanceCount(comp) > 1 && size(children) > 0)
        {
            // The depth-0 call is made with a hand-built map that has no field yet.
            if (parentInfo.assemblyOriginals == undefined)
            {
                parentInfo.assemblyOriginals = [];
            }

            parentInfo.assemblyOriginals = append(parentInfo.assemblyOriginals, children);
        }

        // The mate connectors are created above, before the empty-body `continue`
        // (note 20).

        if (depth == 1)
        {
            const compositePartId = compId + "composite";
            // The originals the recursion collected, which no pattern ever sees.
            var compositeBodies = qUnion([qUnion(children), bodies, qUnion(parentInfo.assemblyOriginals)]);

            // The CP marker rides on the FIRST top-level component's composite
            // part, not on every stage's (note 8).
            if (i == 0 && parentInfo.isFirstTopComponent == true && parentInfo.centerOfPressure != undefined)
            {
                const cpSphereId = compId + "centerOfPressure";
                // OpenRocket measures CP from the tip; transform, don't assume (notes 8).
                const cpCenter = parentInfo.transform * (vector(0, 0, -parentInfo.centerOfPressure) * units);
                opSphere(context, cpSphereId, {
                            // Sized from the widest body tube, with a margin to clear it.
                            "radius" : parentInfo.bodyTubeRadius * units * 1.1 + 0.01 * units,
                            "center" : cpCenter
                        });
                const cpSphere = qCreatedBy(cpSphereId, EntityType.BODY);
                setProperty(context, {
                            "entities" : cpSphere,
                            "propertyType" : PropertyType.NAME,
                            "value" : "Center of Pressure"
                        });
                setProperty(context, {
                            "entities" : cpSphere,
                            "propertyType" : PropertyType.APPEARANCE,
                            "value" : color(1, 0, 0, 0.25)
                        });
                setProperty(context, {
                            "entities" : cpSphere,
                            "propertyType" : PropertyType.MATERIAL,
                            "value" : {
                                "name" : "",
                                "density" : 0 * kilogram / meter ^ 3,
                                "poissonRatio" : 0,
                                "youngsModulus" : 0 * pascal,
                                "tensileYieldStrength" : 0 * pascal,
                                "ultimateTensileStrength" : 0 * pascal,
                                "compressiveYieldStrength" : 0 * pascal,
                                "ultimateCompressiveStrength" : 0 * pascal
                            } as Material
                        });
                compositeBodies = qUnion([compositeBodies, cpSphere]);
            }

            opCreateCompositePart(context, compositePartId, {
                        "bodies" : compositeBodies
                    });

            const composite = qCreatedBy(compositePartId, EntityType.BODY)->qBodyType(BodyType.COMPOSITE);

            if (evaluateQueryCount(context, composite) != 0)
            {
                setProperty(context, {
                            "entities" : composite,
                            "propertyType" : PropertyType.NAME,
                            "value" : comp.name
                        });
            }
        }


    }

    // TEMPORARY: a log WITHOUT this line means something outside a revolve threw
    // (note 13).
    if (DEBUG_ASSEMBLY)
    {
        println("  [done] createComponents depth=" ~ toString(depth)
                ~ " components=" ~ toString(numComponents));
    }

    return qUnion(componentQueryArray);
}

function sketchComponent(context is Context, comp is map, sketch is Sketch, units is ValueWithUnits, sketchPlane is Plane, parentSketch, parentSiblingSketches)
{
    const componentType = comp['type'];

    if (componentType == "nosecone")
    {
        noseComponentSketch(comp, sketch, units);
    }
    else if (componentType == "bodytube")
    {
        bodyComponentSketch(comp, sketch, units);
    }
    else if (componentType == "innertube")
    {
        innertubeComponentSketch(comp, sketch, units);
    }
    else if (componentType == "tubecoupler")
    {
        tubecouplerComponentSketch(comp, sketch, units);
    }
    else if (componentType == "engineblock")
    {
        engineblockComponentSketch(comp, sketch, units);
    }
    else if (componentType == "transition")
    {
        transitionComponentSketch(comp, sketch, units);
    }
    else if (componentType == "trapezoidfinset")
    {
        trapezoidfinsetComponentSketch(context, comp, sketch, units, sketchPlane, parentSketch, parentSiblingSketches);
    }
    else if (componentType == "ellipticalfinset")
    {
        ellipticalfinsetComponentSketch(context, comp, sketch, units, sketchPlane, parentSketch, parentSiblingSketches);
    }
    else if (componentType == "shockcord")
    {
        shockcordComponentSketch(comp, sketch, units);
    }
    else if (componentType == "parachute")
    {
        parachuteComponentSketch(comp, sketch, units);
    }
    else if (componentType == "launchlug")
    {
        launchlugComponentSketch(comp, sketch, units);
    }
    else if (componentType == "masscomponent")
    {
        masscomponentComponentSketch(comp, sketch, units);
    }
    else if (componentType == "centeringring")
    {
        centeringringComponentSketch(comp, sketch, units);
    }
    else if (componentType == "freeformfinset")
    {
        freeformfinsetComponentSketch(context, comp, sketch, units, sketchPlane, parentSketch, parentSiblingSketches);
    }
    else if (componentType == "tubefinset")
    {
        tubefinsetComponentSketch(comp, sketch, units);
    }
    else if (componentType == "bulkhead")
    {
        bulkheadComponentSketch(comp, sketch, units);
    }
    else if (componentType == "railbutton")
    {
        railbuttonComponentSketch(comp, sketch, units);
    }
    else if (componentType == "streamer")
    {
        streamerComponentSketch(comp, sketch, units);
    }
}

function completeComponent(context is Context, comp is map, sketchFace, tform is Transform, id is Id, units is ValueWithUnits, children, depth is number, parentSketch, motorOptions is map)
{
    const compType = comp['type'];
    var resultQuery = qUnion([]);
    const params = comp.params;

    var instanceCount = 1;

    if (comp.position != undefined && comp.position.instanceCount != undefined)
    {
        instanceCount = comp.position.instanceCount;
    }

    if (sketchFace != undefined)
    {
        if (compType == "ellipticalfinset")
        {
            // Keep the sketch flat. Cant is applied to the resulting solid
            // before the angular instances are patterned.
            resultQuery = buildFinBody(context, comp, id, sketchFace, tform, units,
                        (tform * FRONT_SKETCH_PLANE).linear * (vector(0, 0, 1) * units));

            // The tab is unioned on BEFORE the cant, so both cant together (note 15).
            resultQuery = unionFinTab(context, comp, id, tform, units, resultQuery,
                        (tform * FRONT_SKETCH_PLANE).linear * (vector(0, 0, 1) * units),
                        parentSketch);

            resultQuery = applyFinCant(context, comp, id, tform, units, resultQuery);
            instanceCount = params.finCount;
        }
        else if (compType == "trapezoidfinset" || compType == "freeformfinset")
        {
            resultQuery = buildFinBody(context, comp, id, sketchFace, tform, units,
                        tform.linear * (vector(0, 1, 0) * units));

            // The union happens before the pattern, so instances carry their tabs.
            resultQuery = unionFinTab(context, comp, id, tform, units, resultQuery,
                        tform.linear * (vector(0, 1, 0) * units),
                        parentSketch);

            // Cant applies to these exactly as it does to an elliptical fin.
            resultQuery = applyFinCant(context, comp, id, tform, units, resultQuery);

            instanceCount = params.finCount;
        }
        else
        {
            if (compType == "launchlug")
            {
                const centerOffset = params.offsetRadius + params.outerRadius;
                tform *= transform(vector(centerOffset, 0, 0) * units);
            }

            if (compType == "railbutton")
            {
                tform *= transformRot(rotationMatrix3dEulerXYZ(vector(0, PI / 2, 0) * radian));
            }

            const revolveId = id + "revolve";

            // A tube fin revolves about its own axis, not the rocket axis (notes 6).
            var revolveOrigin = tform.translation;
            if (compType == "tubefinset")
            {
                const centerOffset = (params.offsetRadius == undefined ? 0 : params.offsetRadius) + params.outerRadius;
                revolveOrigin = revolveOrigin + tform.linear * (vector(centerOffset, 0, 0) * units);
            }
            const upAxis = line(revolveOrigin, tform.linear * vector(0, 0, 1));

            // The try/catch is load-bearing, and `revolveFailed` has to be carried
            // out: FeatureScript cannot `continue` out of a catch (notes 11, 14).
            var revolveFailed = false;

            if (DEBUG_ASSEMBLY)
            {
                println("  [revolve] " ~ comp.name ~ " (" ~ compType ~ ") depth=" ~ toString(depth)
                        ~ " face=" ~ toString(sketchFace != undefined)
                        ~ describeSection(comp));
            }

            try
            {
                opRevolve(context, revolveId, {
                            "entities" : sketchFace,
                            "axis" : upAxis,
                            "angleForward" : 2 * PI * radian
                        });
            }
            catch(revolveError)
            {
                revolveFailed = true;
                // A failure, not chatter: kept past the release build's stripping.
                // @keep
                println("  [revolve] CAUGHT " ~ comp.name ~ " (" ~ compType ~ "): "
                        ~ toString(revolveError));
            }

            resultQuery = qCreatedBy(revolveId, EntityType.BODY);

            const revolveOk = evaluateQueryCount(context, resultQuery) != 0;

            // Report the outcome, so "the log stops here" cannot mean two things
            // (note 13). The failure it reports is already logged above.
            if (DEBUG_ASSEMBLY)
            {
                println("  [revolve] DONE " ~ comp.name ~ " (" ~ compType ~ ") ok="
                        ~ toString(revolveOk) ~ " bodies="
                        ~ toString(evaluateQueryCount(context, resultQuery))
                        ~ (revolveFailed ? " THREW" : ""));
            }

            // A failed revolve contributes no body, and the steps below need one.
            if (revolveOk && (compType == "nosecone" || compType == "transition"))
            {
                // Each shoulder is its own polygon, revolved separately and unioned
                // on (note 18).
                resultQuery = unionShoulders(context, comp, id, tform, units, resultQuery);
            }

            if (revolveOk && (compType == "shockcord" || compType == "parachute"))
            {
                const edgeQueries = qCreatedBy(revolveId, EntityType.EDGE);
                opFillet(context, id + "fillet1", {
                            "entities" : edgeQueries,
                            "radius" : min(params.packedLength / 4, params.packedRadius / 2)
                        });
            }

            // A motor mount gets its motor as a child of the mount, not the rocket
            // (note 16).
            if (revolveOk)
            {
                resultQuery = addMotor(context, comp, id, tform, units, resultQuery, motorOptions);
            }
        }
    }

    if (compType == "tubefinset")
    {
        instanceCount = params.finCount;
    }

    if (instanceCount > 1)
    {
        var transforms = makeArray(instanceCount - 1);
        var instanceNames = makeArray(instanceCount - 1);

        if (isLineInstanceable(compType))
        {
            const instanceSeparation = comp.position.instanceSeparation;
            // linear instances: stack along the body's own axis, stepping aft by
            // the separation for each additional copy (note 19).
            for (var i = 1; i < instanceCount; i += 1)
            {
                transforms[i - 1] = transform(vector(0, 0, -instanceSeparation * i) * units);
                instanceNames[i - 1] = "" ~ i;
            }
        }
        else
        {
            // Angular instances: the axis is Z_AXIS for an assembly and the
            // body's own axis for everything else (note 19).
            const instanceAxis = isAssembly(compType)
                ? Z_AXIS
                : line(tform.translation, tform.linear * vector(0, 0, 1));

            const deltaAngle = 2 * PI / instanceCount;
            for (var i = 1; i < instanceCount; i += 1)
            {
                transforms[i - 1] = rotationAround(instanceAxis, deltaAngle * i * radian);
                instanceNames[i - 1] = "" ~ i;
            }
        }

        var patternQuery = resultQuery;

        if (canBeQuery(children))
        {
            patternQuery = qUnion([resultQuery, children]);
        }

        // opPattern throws on an empty entity set, so count the bodies first
        // (note 18).
        if (evaluateQueryCount(context, patternQuery) == 0)
        {
            if (DEBUG_ASSEMBLY)
            {
                println("  [asm] " ~ comp.name ~ " (" ~ compType ~ ") has nothing to pattern"
                        ~ " (instances=" ~ toString(instanceCount) ~ ")");
            }
        }
        else
        {
            const patternId = id + "pattern1";
            try
            {
                opPattern(context, patternId, {
                            "entities" : patternQuery,
                            "transforms" : transforms,
                            "instanceNames" : instanceNames
                        });
            }
            catch(patternError)
            {
                // @keep -- a failure the user can act on, not routine chatter
                println("  [asm] CAUGHT pattern on " ~ comp.name ~ " (" ~ compType
                        ~ ", instances=" ~ toString(instanceCount) ~ "): " ~ toString(patternError));
            }

            if (DEBUG_ASSEMBLY)
            {
                const patternedBodies = evaluateQueryCount(context, qCreatedBy(patternId, EntityType.BODY));
                if (patternedBodies == 0)
                {
                    println("  [asm] " ~ comp.name ~ " (" ~ compType ~ ") pattern produced no bodies"
                            ~ " (instances=" ~ toString(instanceCount) ~ ", transforms=" ~ toString(size(transforms)) ~ ")");
                }
            }

            // Only the copies opPattern created, never the originals (notes 3).
            resultQuery = qUnion([resultQuery, qCreatedBy(patternId, EntityType.BODY)]);
        }
    }
    else if (isAssembly(compType) && canBeQuery(children))
    {
        resultQuery = children;   // single-instance assembly (notes 3)
    }

    return resultQuery;
}

/** Revolve and union each of a component's shoulders onto its body (note 18). */
function unionShoulders(context is Context, comp is map, id is Id, tform is Transform, units is ValueWithUnits, baseQuery is Query) returns Query
{
    var resultQuery = baseQuery;

    const shoulderData = comp.params.shoulderProfile;
    if (shoulderData == undefined)
        return resultQuery;

    // The component's own plane and revolve axis, so the shoulder lands on the
    // body it belongs to.
    const shoulderPlane = plane(transformToCoordSystem(tform * FRONT_SKETCH_PLANE));
    const upAxis = line(tform.translation, tform.linear * vector(0, 0, 1));

    const ends = ["fore", "aft"];
    for (var i = 0; i < size(ends); i += 1)
    {
        const which = ends[i];
        if (shoulderData[which] == undefined)
            continue;

        // `~` concatenates and `+` builds an Id, so the name is assembled first.
        const shoulderId = id + ("shoulder" ~ which);

        const shoulderSketch = newSketchOnPlane(context, shoulderId + "sketch", {
                    "sketchPlane" : shoulderPlane
                });

        sketchShoulder(comp, shoulderSketch, units, which);

        skSolve(shoulderSketch);

        const shoulderFaces = evaluateQuery(context, qSketchRegion(shoulderId + "sketch"));

        // TEMPORARY diagnostic: this path is unproven, the body revolve has always
        // failed before reaching it (note 13).
        if (DEBUG_ASSEMBLY)
        {
            println("  [shoulder] " ~ comp.name ~ " " ~ which ~ " faces=" ~ toString(size(shoulderFaces)));
        }

        if (size(shoulderFaces) == 0)
        {
            if (DEBUG_ASSEMBLY)
            {
                println("  [asm] " ~ comp.name ~ " (" ~ comp['type'] ~ ") " ~ which
                        ~ " shoulder solved to no region — shoulder skipped");
            }
            continue;
        }

        // Caught as in `completeComponent`, so one bad shoulder cannot abort the
        // components after it (note 14).
        try
        {
            opRevolve(context, shoulderId + "revolve", {
                        "entities" : shoulderFaces[0],
                        "axis" : upAxis,
                        "angleForward" : 2 * PI * radian
                    });
        }
        catch(shoulderError)
        {
            // @keep -- a failure the user can act on, not routine chatter
            println("  [shoulder] CAUGHT " ~ comp.name ~ " " ~ which ~ ": "
                    ~ toString(shoulderError));
            continue;
        }

        const shoulderQuery = qCreatedBy(shoulderId + "revolve", EntityType.BODY);
        if (evaluateQueryCount(context, shoulderQuery) == 0)
        {
            if (DEBUG_ASSEMBLY)
            {
                println("  [asm] " ~ comp.name ~ " (" ~ comp['type'] ~ ") " ~ which
                        ~ " shoulder revolve produced no body — shoulder skipped");
            }
            continue;
        }

        // Plain UNION, no `targets`: the earliest body in `tools` keeps its
        // identity, and `tools` must be a Query (note 10).
        opBoolean(context, shoulderId + "union", {
                    "operationType" : BooleanOperationType.UNION,
                    "tools" : qUnion([resultQuery, shoulderQuery]),
                    "makeSolid" : true,
                    "eraseImprintedEdges" : true,
                    "recomputeMatches" : true
                });

        const unionQuery = qCreatedBy(shoulderId + "union", EntityType.BODY);
        if (evaluateQueryCount(context, unionQuery) == 0)
        {
            // Keep the un-unioned body rather than losing the component entirely.
            if (DEBUG_ASSEMBLY)
            {
                println("  [asm] " ~ comp.name ~ " (" ~ comp['type'] ~ ") " ~ which
                        ~ " shoulder union produced no body — keeping the body alone");
            }
            continue;
        }

        resultQuery = unionQuery;
    }

    return resultQuery;
}

/** Cant a fin set: roll the solid about the fin's span axis, through the mid-point
 *  of its root chord.  Applied to the solid, after the tab (notes 15, 29). */
function applyFinCant(context is Context, comp is map, id is Id, tform is Transform, units is ValueWithUnits, baseQuery is Query) returns Query
{
    const params = comp.params;
    const cantAngle = params.cantAngle == undefined ? 0 : params.cantAngle;
    if (abs(cantAngle) <= 1e-9)
    {
        return baseQuery;
    }

    const finPlaneTransform = tform * FRONT_SKETCH_PLANE;
    const offsetRadius = params.offsetRadius == undefined ? 0 : params.offsetRadius;
    const finCenter = finPlaneTransform
            * (vector(offsetRadius, -finRootChord(params) / 2, 0) * units);
    opTransform(context, id + "cant", {
                "bodies" : baseQuery,
                "transform" : rotationAround(
                    line(finCenter, finPlaneTransform.linear * X_DIRECTION),
                    -cantAngle * radian
                )
            });

    // opTransform updates the existing bodies in place, so the ORIGINAL query is
    // still the right pattern source -- qCreatedBy would not be.
    return baseQuery;
}

/** A fin's solid, honouring its cross-section (note 23, component_sketches.fs). */
function buildFinBody(context is Context, comp is map, id is Id, sketchFace, tform is Transform, units is ValueWithUnits, extrudeDirection is Vector) returns Query
{
    const params = comp.params;
    const crossSection = params.crossSection == undefined ? "square" : params.crossSection;
    const thickness = params.thickness * units;

    // The proven path, and the fallback for everything else.
    if (crossSection != "rounded" && crossSection != "airfoil")
    {
        return extrudeFinPlate(context, id, sketchFace, extrudeDirection, thickness);
    }

    // The fin's own plane: its x is the span (radial) direction.
    const finPlane = plane(transformToCoordSystem(tform * FRONT_SKETCH_PLANE));
    const spanDir = finPlane.x;
    const foreRootPoint = finPlane.origin + spanDir * ((params.offsetRadius == undefined ? 0 : params.offsetRadius) * units);

    // 1. The section, normal to the span: +x is thickness, +y runs aft.
    const sectionId = id + "sectionSketch";
    const sectionSketch = newSketchOnPlane(context, sectionId, {
                "sketchPlane" : plane(foreRootPoint, spanDir, extrudeDirection)
            });

    finCrossSectionProfile(comp, sectionSketch, units, finRootChord(params), params.thickness);
    skSolve(sectionSketch);

    const sectionFaces = evaluateQuery(context, qSketchRegion(sectionId));
    if (size(sectionFaces) == 0)
    {
        if (DEBUG_ASSEMBLY)
        {
            println("  [section] " ~ comp.name ~ " (" ~ comp['type'] ~ ") " ~ crossSection
                    ~ " section solved to no region — using a square section");
        }
        return extrudeFinPlate(context, id, sketchFace, extrudeDirection, thickness);
    }

    // Extrude the section radially: from the root outward, over the fin's span.
    var sectionBody = qNothing();
    try
    {
        opExtrude(context, id + "sectionSweep", {
                    "entities" : sectionFaces[0],
                    "direction" : spanDir,
                    "endBound" : BoundingType.BLIND,
                    "endDepth" : finSpanExtent(params) * units,
                    "startBound" : BoundingType.BLIND,
                    "startDepth" : 0
                });
        sectionBody = qCreatedBy(id + "sectionSweep", EntityType.BODY);
    }
    catch(sectionError)
    {
        // @keep -- a failure the user can act on, not routine chatter
        println("  [section] CAUGHT " ~ comp.name ~ " (" ~ comp['type'] ~ "): " ~ toString(sectionError));
        return extrudeFinPlate(context, id, sketchFace, extrudeDirection, thickness);
    }

    if (evaluateQueryCount(context, sectionBody) == 0)
    {
        if (DEBUG_ASSEMBLY)
        {
            println("  [section] " ~ comp.name ~ " (" ~ comp['type'] ~ ") " ~ crossSection
                    ~ " section extrude produced no body — using a square section");
        }
        return extrudeFinPlate(context, id, sketchFace, extrudeDirection, thickness);
    }

    return trimSectionToPlanform(context, comp, id, sketchFace, extrudeDirection, thickness,
                sectionBody, crossSection);
}

/** Steps 2 and 3 of the section build: slab the planform, then keep the overlap. */
function trimSectionToPlanform(context is Context, comp is map, id is Id, sketchFace, extrudeDirection is Vector, thickness, sectionBody is Query, crossSection is string) returns Query
{
    // The planform as a slab, thick enough to contain the section anywhere.
    const slabId = id + "sectionSlab";
    var slabBody = qNothing();
    try
    {
        opExtrude(context, slabId, {
                    "entities" : sketchFace,
                    "direction" : extrudeDirection,
                    "endBound" : BoundingType.BLIND,
                    "endDepth" : thickness * 2,
                    "startBound" : BoundingType.BLIND,
                    "startDepth" : thickness * 2
                });
        slabBody = qCreatedBy(slabId, EntityType.BODY);
    }
    catch(slabError)
    {
        // @keep -- a failure the user can act on, not routine chatter
        println("  [section] CAUGHT " ~ comp.name ~ " (" ~ comp['type'] ~ "): " ~ toString(slabError));
        return extrudeFinPlate(context, id, sketchFace, extrudeDirection, thickness);
    }

    if (evaluateQueryCount(context, slabBody) == 0)
    {
        return extrudeFinPlate(context, id, sketchFace, extrudeDirection, thickness);
    }

    // Keep what the planform allows; the slab goes first so the fin keeps its
    // identity (note 10).
    const trimId = id + "sectionTrim";
    try
    {
        opBoolean(context, trimId, {
                    // INTERSECTION, not INTERSECT: that is the enum member.
                    "operationType" : BooleanOperationType.INTERSECTION,
                    "tools" : qUnion([slabBody, sectionBody]),
                    "makeSolid" : true,
                    "eraseImprintedEdges" : true,
                    "recomputeMatches" : true
                });
    }
    catch(trimError)
    {
        // @keep -- a failure the user can act on, not routine chatter
        println("  [section] CAUGHT " ~ comp.name ~ " (" ~ comp['type'] ~ "): " ~ toString(trimError));
        return extrudeFinPlate(context, id, sketchFace, extrudeDirection, thickness);
    }

    const trimmed = qCreatedBy(trimId, EntityType.BODY);
    if (evaluateQueryCount(context, trimmed) == 0)
    {
        // An empty intersection means the two solids never met; keep the plate.
        if (DEBUG_ASSEMBLY)
        {
            println("  [section] " ~ comp.name ~ " (" ~ comp['type'] ~ ") " ~ crossSection
                    ~ " intersect produced no body — using a square section");
        }
        return extrudeFinPlate(context, id, sketchFace, extrudeDirection, thickness);
    }

    return trimmed;
}

/** How far the fin reaches along its span; the intersect trims it back anyway. */
function finSpanExtent(params is map) returns number
{
    if (params.height != undefined && params.height > 0)
    {
        return params.height;
    }
    // A freeform fin has no `height`; its extent is the planform's own y range.
    const points = params.points;
    if (points == undefined)
    {
        return 0;
    }
    var tallest = 0;
    for (var i = 0; i < size(points); i += 1)
    {
        tallest = max(tallest, points[i][1]);
    }
    return tallest;
}

/** The plain symmetric plate, centred on the fin's mid-surface. */
function extrudeFinPlate(context is Context, id is Id, sketchFace, extrudeDirection is Vector, thickness) returns Query
{
    const extrudeId = id + "extrude1";
    opExtrude(context, extrudeId, {
                "entities" : sketchFace,
                "direction" : extrudeDirection,
                "endBound" : BoundingType.BLIND,
                "endDepth" : thickness / 2,
                "startBound" : BoundingType.BLIND,
                "startDepth" : thickness / 2
            });
    return qCreatedBy(extrudeId, EntityType.BODY);
}

/** Extrude a fin's tab as its own body and union it onto the fin (note 15). */
function unionFinTab(context is Context, comp is map, id is Id, tform is Transform, units is ValueWithUnits, baseQuery is Query, extrudeDirection is Vector, parentSketch) returns Query
{
    if (!finHasTab(comp.params))
        return baseQuery;

    // The fin's own plane, so the tab lands where the fin is and the parent's
    // surface projects onto the root's 2D frame.
    const tabPlane = plane(transformToCoordSystem(tform * FRONT_SKETCH_PLANE));
    const tabSketchId = id + "tabSketch";

    // New sketch through union, all inside ONE `try`, so a tab that cannot be
    // built costs the tab and not the rocket (note 14).
    try
    {
        const tabSketch = newSketchOnPlane(context, tabSketchId, {
                    "sketchPlane" : tabPlane
                });

        if (!sketchFinTab(context, comp, tabSketch, units, tabPlane, parentSketch))
        {
            // No tab, or no parent surface for it to pass through.  Nothing drawn.
            return baseQuery;
        }

        skSolve(tabSketch);

        const tabFaces = evaluateQuery(context, qSketchRegion(tabSketchId));
        const faceCount = size(tabFaces);

        // Whether the region formed, for debugging a tab that did not appear.
        // The failure itself is reported unconditionally just below.
        if (DEBUG_ASSEMBLY)
        {
            println("  [tab] " ~ comp.name ~ " region faces=" ~ toString(faceCount));
        }

        // What the SOLVED sketch holds, against what it was asked to hold (note 23).
        if (DEBUG_ASSEMBLY)
        {
            reportTabSketchCurves(context, tabSketchId, tabPlane, units, comp.name);
        }

        if (faceCount == 0)
        {
            println("  [tab] " ~ comp.name ~ " (" ~ comp['type'] ~ ") solved to no region -- tab skipped");
            return baseQuery;
        }

        // Same half-thickness either side of the plane as the fin's own extrude.
        const thickness = comp.params.thickness * units;
        const extrudeId = tabSketchId + "extrude";
        opExtrude(context, extrudeId, {
                    "entities" : tabFaces[0],
                    "direction" : extrudeDirection,
                    "endBound" : BoundingType.BLIND,
                    "endDepth" : thickness / 2,
                    "startBound" : BoundingType.BLIND,
                    "startDepth" : thickness / 2
                });

        const tabQuery = qCreatedBy(extrudeId, EntityType.BODY);
        if (evaluateQueryCount(context, tabQuery) == 0)
        {
            println("  [tab] " ~ comp.name ~ " (" ~ comp['type'] ~ ") extrude produced no body -- tab skipped");
            return baseQuery;
        }

        // Plain UNION with no `targets`, parent first so the fin keeps its identity.
        opBoolean(context, tabSketchId + "union", {
                    "operationType" : BooleanOperationType.UNION,
                    "tools" : qUnion([baseQuery, tabQuery]),
                    "makeSolid" : true,
                    "eraseImprintedEdges" : true,
                    "recomputeMatches" : true
                });

        const unionQuery = qCreatedBy(tabSketchId + "union", EntityType.BODY);
        if (evaluateQueryCount(context, unionQuery) == 0)
        {
            // Two solids that merely TOUCH are the usual cause (note 25,
            // component_sketches.fs).  Keep the un-unioned fin.
            println("  [tab] " ~ comp.name ~ " (" ~ comp['type'] ~ ") union produced no body -- keeping the fin alone");
            return baseQuery;
        }

        return unionQuery;
    }
    catch(tabError)
    {
        // @keep -- a failure the user can act on, not routine chatter
        println("  [tab] CAUGHT " ~ comp.name ~ " (" ~ comp['type'] ~ "): " ~ toString(tabError));
        return baseQuery;
    }
}

/** The motor in a motor mount, as a cylinder coaxial with the mount (note 16). */
function addMotor(context is Context, comp is map, id is Id, tform is Transform, units is ValueWithUnits, baseQuery is Query, motorOptions is map) returns Query
{
    var resultQuery = baseQuery;

    const params = comp.params;
    if (params.isMotorMount != true)
    {
        return resultQuery;
    }

    const mount = params.motorMount;
    if (mount == undefined)
    {
        return resultQuery;
    }

    // Radius and length; the length is an OVERRIDE, and a raw number meets a real
    // LENGTH only after the division (note 16, and note 21 of component_sketches).
    const diameter = mount.diameter == undefined ? 0 : mount.diameter;
    var motorLength = mount.length == undefined ? 0 : mount.length;
    const overrideLength = motorOptions == undefined ? 0 * meter : motorOptions["overrideLength"];
    if (overrideLength > 0 * meter)
    {
        motorLength = overrideLength / units;
    }

    const radius = diameter / 2;
    const mountLength = params.length == undefined ? 0 : params.length;

    // Nothing to draw without a radius and a length; invent neither.
    if (radius <= 1e-9 || motorLength <= 1e-9)
    {
        if (DEBUG_ASSEMBLY)
        {
            println("  [motor] " ~ comp.name ~ " (" ~ comp['type'] ~ ") has no motor selected — no motor geometry");
        }
        return resultQuery;
    }

    // An overhanging motor is legal, so draw it where the formula lands.
    const motorFore = mountLength - motorLength + (mount.overhang == undefined ? 0 : mount.overhang);

    // The mount's own meridian plane, so the motor is coaxial with the tube.
    const sketchId = id + "motorSketch";
    const motorSketch = newSketchOnPlane(context, sketchId, {
                "sketchPlane" : plane(transformToCoordSystem(tform * FRONT_SKETCH_PLANE))
            });

    // y runs aft-negative and the sketch's origin is the mount's FORE end.
    motorSectionSketch(motorSketch, radius, -motorFore * units, -(motorFore + motorLength) * units, units);
    skSolve(motorSketch);

    const motorFaces = evaluateQuery(context, qSketchRegion(sketchId));
    if (size(motorFaces) == 0)
    {
        if (DEBUG_ASSEMBLY)
        {
            println("  [motor] " ~ comp.name ~ " (" ~ comp['type'] ~ ") section solved to no region — no motor geometry");
        }
        return resultQuery;
    }

    // Revolved about the mount's own axis, the one its wall was revolved about.
    const motorId = id + "motorRevolve";
    try
    {
        opRevolve(context, motorId, {
                    "entities" : motorFaces[0],
                    "axis" : line(tform.translation, tform.linear * vector(0, 0, 1)),
                    "angleForward" : 2 * PI * radian
                });
    }
    catch(motorError)
    {
        // @keep -- a failure the user can act on, not routine chatter
        println("  [motor] CAUGHT " ~ comp.name ~ " (" ~ comp['type'] ~ "): " ~ toString(motorError));
        return resultQuery;
    }

    const motorQuery = qCreatedBy(motorId, EntityType.BODY);
    if (evaluateQueryCount(context, motorQuery) == 0)
    {
        if (DEBUG_ASSEMBLY)
        {
            println("  [motor] " ~ comp.name ~ " (" ~ comp['type'] ~ ") revolve produced no body — no motor geometry");
        }
        return resultQuery;
    }

    // Named here, while the body is still in hand; restyleMotor re-asserts it
    // after the mount's rename, which lands on this body too (note 16).
    styleMotor(context, motorQuery, mount, motorOptions);

    applyMotorMass(context, motorQuery, comp, motorOptions);

    // Appended, not unioned: a union would fill the mount's air gap (note 16).
    resultQuery = qUnion([resultQuery, motorQuery]);
    return resultQuery;
}

/** A name for the motor body: the mass that weights it, else the designation
 *  (notes 16, 28). */
function motorLabel(mount is map, motorOptions is map) returns string
{
    const massGrams = motorOptions == undefined ? 0 : motorOptions["massGrams"];

    if (massGrams > 0)
    {
        return "Motor - " ~ formatGrams(massGrams) ~ "g";
    }

    const designation = mount.designation == undefined ? "" : mount.designation;
    if (designation == "")
    {
        return "Motor";
    }
    return "Motor - " ~ designation;
}

/** Grams without a pointless decimal point: 24, not 24.0. */
function formatGrams(massGrams is number) returns string
{
    const rounded = round(massGrams * 10) / 10;
    if (rounded == floor(rounded))
    {
        return "" ~ floor(rounded);
    }
    return "" ~ rounded;
}

/** Re-assert the motor's name and colour after the mount's own properties, which
 *  are set on every body the mount produced, the motor included (note 28). */
function restyleMotor(context is Context, completeId is Id, comp is map, motorOptions is map)
{
    const params = comp.params;
    if (params.isMotorMount != true || params.motorMount == undefined)
    {
        return;
    }

    const motorQuery = qCreatedBy(completeId + "motorRevolve", EntityType.BODY);
    const found = evaluateQueryCount(context, motorQuery);

    if (DEBUG_ASSEMBLY)
    {
        println("  [motor] restyle " ~ comp.name ~ " motorBodies=" ~ toString(found)
                ~ " -> " ~ motorLabel(params.motorMount, motorOptions)
                ~ (found == 0 ? "  (NOT FOUND — motor will show as the mount's name)" : ""));
    }

    if (found == 0)
    {
        return;
    }

    styleMotor(context, motorQuery, params.motorMount, motorOptions);
}

/** The motor's own name and colour, applied to the body directly rather than
 *  looked up (note 28). */
function styleMotor(context is Context, motorQuery is Query, mount is map, motorOptions is map)
{
    setProperty(context, {
                "entities" : motorQuery,
                "propertyType" : PropertyType.NAME,
                "value" : motorLabel(mount, motorOptions)
            });

    // A fixed gunmetal rather than the mount's paint: a motor is a bought-in part,
    // and it would otherwise be coloured exactly like the tube it sits in.
    setProperty(context, {
                "entities" : motorQuery,
                "propertyType" : PropertyType.APPEARANCE,
                "value" : color(0.22, 0.22, 0.25, 1)
            });
}

/** Apply the motor's mass as an explicit override, and say what was done (note 16). */
function applyMotorMass(context is Context, motorQuery is Query, comp is map, motorOptions is map)
{
    const massGrams = motorOptions == undefined ? 0 : motorOptions["massGrams"];

    if (massGrams <= 0)
    {
        // @keep: tells the user which field to fill in, so it has to reach them.
        println("  [motor] " ~ comp.name ~ " (" ~ comp['type'] ~ ") has no motor mass set — set \"Motor mass (g)\" on the feature to weight it");
        return;
    }

    // Grams to kilograms: a bare ratio, attached to a unit only here (note 21 of
    // component_sketches.fs).
    const massKilograms = massGrams / 1000;

    try
    {
        setProperty(context, {
                    "entities" : motorQuery,
                    "propertyType" : PropertyType.MASS_OVERRIDE,
                    "value" : massKilograms * kilogram
                });
    }
    catch(massError)
    {
        // @keep -- a failure the user can act on, not routine chatter
        println("  [motor] CAUGHT mass override on " ~ comp.name ~ ": " ~ toString(massError));
    }
}

/** A human-readable dump of a revolved component's meridian section (note 11). */
function describeSection(comp is map) returns string
{
    const params = comp.params;

    // A nose cone / transition carries a computed section; name only the
    // primitive parameters actually present.
    if (params.profile == undefined)
    {
        var prim = " [no profile";
        if (params.packedRadius != undefined)
        {
            prim = prim ~ " packedRadius=" ~ toString(params.packedRadius);
        }
        if (params.packedLength != undefined)
        {
            prim = prim ~ " packedLength=" ~ toString(params.packedLength);
        }
        if (params.outerRadius != undefined)
        {
            prim = prim ~ " outerRadius=" ~ toString(params.outerRadius);
        }
        if (params.innerRadius != undefined)
        {
            prim = prim ~ " innerRadius=" ~ toString(params.innerRadius);
        }
        return prim ~ "]";
    }

    var out = " section n=" ~ toString(size(params.profile));

    if (params.innerProfile != undefined)
    {
        out = out ~ " bore n=" ~ toString(size(params.innerProfile));
    }

    out = out ~ " innerIsAxis=" ~ toString(params.innerIsAxis == true)
            ~ " shoulders=" ~ shoulderSummary(params);

    const outerR = minRadiusOf(params.profile);

    // Bare numbers in the payload's own units, so both branches must be numbers.
    var innerR = 0;
    if (params.innerProfile != undefined)
    {
        innerR = minRadiusOf(params.innerProfile);
    }

    out = out ~ " outerMinR=" ~ toString(outerR)
            ~ " innerMinR=" ~ toString(innerR);

    // A mass object has `packedLength`, so report `length` only when it is there.
    if (params.length != undefined)
    {
        out = out ~ " length=" ~ toString(params.length);
    }

    return out;
}

/** Smallest radius in a serialized profile; RAW numbers, so it returns a
 * `number` (note 21 of component_sketches.fs). */
function minRadiusOf(points is array) returns number
{
    var smallest = 1;
    for (var i = 0; i < size(points); i += 1)
    {
        smallest = min(smallest, points[i][0]);
    }
    return smallest;
}

/** "fore+aft" / "fore" / "aft" / "none" -- which ends carry a shoulder polygon. */
function shoulderSummary(params) returns string
{
    if (params.shoulderProfile == undefined)
        return "absent";

    const fore = params.shoulderProfile.fore != undefined;
    const aft = params.shoulderProfile.aft != undefined;

    if (fore && aft)
        return "fore+aft";
    if (fore)
        return "fore";
    if (aft)
        return "aft";
    return "none";
}

/** A pod set or parallel stage: a frame for other components, with no body of its own. */
function isAssembly(compType is string) returns boolean
{
    return compType == "podset" || compType == "parallelstage";
}

/** How many instances `completeComponent` will build for `comp`.  Mirrors the fin
 *  overrides it applies, so a caller cannot disagree with it (notes 33, 34). */
function effectiveInstanceCount(comp is map) returns number
{
    const compType = comp['type'];

    if (compType == "ellipticalfinset" || compType == "trapezoidfinset"
        || compType == "freeformfinset" || compType == "tubefinset")
    {
        if (comp.params != undefined && comp.params.finCount != undefined)
        {
            return comp.params.finCount;
        }
    }

    if (comp.position != undefined && comp.position.instanceCount != undefined)
    {
        return comp.position.instanceCount;
    }

    return 1;
}

// OpenRocket's LineInstanceable types: instances stack along the axis, not round it (note 33).
function isLineInstanceable(compType is string) returns boolean
{
    return compType == "launchlug"
        || compType == "railbutton"
        || compType == "centeringring"
        || compType == "bulkhead";
}

function resolveTransform(transformData is map, units is ValueWithUnits, tform is Transform, baseTransform is Transform, length is ValueWithUnits, parentLength) returns array
{
    var newTransform = tform;
    var newLastTransform = tform;

    const axialMethod = transformData.axialMethod;

    if (axialMethod == "after")
    {
        newLastTransform *= (transform(vector(0 * units, 0 * units, -length)));
    }
    else if (axialMethod == "absolute")
    {
        newTransform = toWorld(WORLD_COORD_SYSTEM);
        newLastTransform *= transform(vector(0 * units, 0 * units, -length));
    }
    else if (axialMethod == "top")
    {
        newTransform = baseTransform;
        newLastTransform *= transform(vector(0 * units, 0 * units, -length));
    }
    else if (axialMethod == "bottom")
    {
        newTransform = baseTransform * (transform(vector(0 * units, 0 * units, length - parentLength)));
    }
    else if (axialMethod == "middle" && parentLength != undefined)
    {
        newTransform = baseTransform * (transform(vector(0 * units, 0 * units, length / 2 - parentLength / 2)));
    }

    const axialOffset = transformData.axialOffset;
    if (axialOffset != undefined)
    {
        newTransform *= (transform(vector(0, 0, -axialOffset) * units));
    }

    // RELATIVE adds the stored offset to the parent's angle, already carried by
    // `newTransform`.  FIXED is the other branch and is deliberately EMPTY (note 31).
    const angleMethod = transformData.angleMethod;
    if (angleMethod == "relative")
    {
        const angle = transformData.angleOffset;
        if (angle != undefined && angle != 0)
        {
            const rotationTrans = transformRot(rotationMatrix3d(Z_DIRECTION, angle * radian));

            newTransform *= rotationTrans;
        }
    }

    const radialDirection = transformData.radialDirection;
    if (radialDirection != undefined && radialDirection != 0)
    {
        newTransform *= transformRot(rotationMatrix3dEulerXYZ(vector(0, 0, radialDirection) * radian));
    }

    const radialPosition = transformData.radialPosition;
    if (radialPosition != undefined)
    {
        newTransform *= (transform(vector(radialPosition, 0, 0) * units));
    }

    // Only components the web app gave a `parentRadius` reach these branches;
    // surface-mounted parts use `offsetRadius` instead (notes 2, 30).
    const radiusOffset = transformData.radiusOffset;
    if (radiusOffset != undefined)
    {
        const parentRadius = transformData.parentRadius;
        if (transformData.radiusMethod == "relative" && parentRadius != undefined)
        {
            // Measured from the parent's surface, so add its radius.
            newTransform *= (transform(vector(parentRadius + radiusOffset, 0, 0) * units));
        }
        else if (transformData.radiusMethod == "surface" && parentRadius != undefined)
        {
            // SURFACE is RELATIVE with a zero offset: the stored value is NOT
            // added, which is what upstream does (note 32).
            newTransform *= (transform(vector(parentRadius, 0, 0) * units));
        }
        else if (transformData.radiusMethod == "free" || transformData.radiusMethod == "absolute")
        {
            // Measured from the parent's centre, i.e. the rocket axis for a pod
            // set; "absolute" is an accepted alias (note 2).
            newTransform *= (transform(vector(radiusOffset, 0, 0) * units));
        }
    }

    return [newTransform, newLastTransform];
}

function determineComponentLength(component is map) returns number
{
    const params = component.params;
    var length = params.length;

    if (length == undefined)
        length = params.rootChord;

    // MassObject components store their length as packedLength (notes 7).
    if (length == undefined)
        length = params.packedLength;

    if (length == undefined)
        length = 0;

    return length;
}

function resolveMaterial(componentMaterial)
{
    if (componentMaterial == undefined)
        return;

    const name = componentMaterial.name;
    const density = componentMaterial.density;

    // TODO: Fix this for imperial
    var densityUnits = kilogram / meter ^ 3;

    return {
                "name" : name,
                "density" : density * densityUnits,
                "poissonRatio" : 0.2,
                "youngsModulus" : 7e10 * pascal,
                "tensileYieldStrength" : 1e9 * pascal,
                "ultimateTensileStrength" : 1.5e8 * pascal,
                "compressiveYieldStrength" : 0 * pascal,
                "ultimateCompressiveStrength" : 0 * pascal
            } as Material;
}

/*
 * ---------------------------------------------------------------------------
 * Notes referenced from the comments above.
 * ---------------------------------------------------------------------------
 *
 * 1. Why children get the parent's siblings as sketch references
 *
 *    A fin's root can outrun its direct parent, for instance a fin on a
 *    transition whose root reaches back over the body tube beside it.  The face
 *    can then only close along the real body profile if the neighbouring
 *    outlines are available too.  These sketches also make the second pass over
 *    each level's components possible, since a child is created after its
 *    siblings' transforms are known.
 *
 *    An earlier revision passed the parent alone, on the reading that
 *    FinSet.getFinFront() takes one mount radius from the direct parent.  That is
 *    true of OpenRocket's own geometry, but it left such a fin with no surface to
 *    close against, so it degenerated to a bare chord.
 *
 * 2. Why the free / absolute radius-offset branch exists
 *
 *    `radiusOffset` has two conventions.  Under "relative" the offset is measured
 *    from the parent's *surface*, so the parent's radius is added to it -- that is
 *    what RadiusMethod.RELATIVE does in OpenRocket, adding the outer radius of a
 *    BodyTube parent.  Under "free" (spelled "absolute" by some writers) it is
 *    measured from the parent's *centre*, which for a pod set is the rocket axis.
 *
 *    Dropping the free branch collapses a pod onto the core, and because the
 *    pod's children are coaxial with it they inherit the collapsed transform, so
 *    their fins end up snapped to the core instead of the pod.  That is what put
 *    the elevator fins at the wrong radius and skewed the rudder.
 *
 * 3. Assemblies: what a component may and may not return
 *
 *    A pod set or parallel stage is a frame for other components.  It has no
 *    sketch of its own, so completeComponent never revolves anything for it and
 *    its own `resultQuery` stays empty; everything visible came from its children.
 *    Two rules follow, and breaking either shows up as a missing component:
 *
 *      - Return only the copies opPattern created.  The original children stay in
 *        the part studio where they were built, and the caller applies NAME,
 *        APPEARANCE and MATERIAL to whatever comes back.  Returning the children
 *        as well therefore renames and recolours every one of them with the
 *        assembly's own values -- which is why the property block is guarded
 *        with !isAssembly instead.
 *      - A single-instance assembly never reaches the pattern branch at all, so it
 *        would return nothing and be dropped by the caller.  It returns its
 *        children instead, which the same property guard then leaves alone.
 *
 *    A Stage reporting that it produced no body is correct rather than a fault: a
 *    stage is a pure container, and its children carry all the geometry.
 *
 * 4. Why a regionless sketch must not `continue`
 *
 *    The first pass over a level's components both builds sketches and records
 *    the per-component entry that the second pass consumes.  A `continue` on an
 *    empty region therefore skips that entry as well, and the component is never
 *    completed: its body never reaches the parent's children query, and any
 *    instancing over that parent silently loses an instance.  An empty region
 *    should only leave the face undefined.
 *
 * 5. Why instances rotate about the rocket axis
 *
 *    Angular instances are placed by rotating the component's radius vector about
 *    the rocket axis, never about the component's own longitudinal axis.  The
 *    latter is a no-op for a body of revolution -- a pod is symmetric about its own
 *    axis -- so every instance lands on top of the first while the count still
 *    looks right.  This matches PodSet.getInstanceOffsets, which returns
 *    (0, radius*cos(angle), radius*sin(angle)) for each instance.
 *
 *    This is stated for an ASSEMBLY, and it is the whole truth only there.  A fin
 *    set's instances orbit the body it is mounted on, which is the rocket axis
 *    for a fin on the centreline and something else entirely for a fin on a pod.
 *    See note 19 for the two cases and how the axis is chosen.
 *
 * 6. Why a tube fin revolves about its own axis
 *
 *    A tube fin is a hollow cylinder parallel to the rocket axis but offset so it
 *    touches the parent body.  Its sketch is an annular section in the meridian
 *    plane, so revolving it about the rocket axis would sweep the annulus around
 *    the wrong centre.  The revolve origin is shifted by the fin's touch radius
 *    plus its outer radius, and the axis is that tube's own line.
 *
 * 7. Why MassObject length falls back to packedLength
 *
 *    RecoveryDevice/MassObject components -- including mass components such as
 *    U-bolts -- store their axial length as packedLength, and OpenRocket's
 *    MassObject.getLength() returns exactly that.  AxialMethod.MIDDLE then uses it
 *    to place the component's centre on the parent's centre, so treating the
 *    length as zero would put the component's *top* there instead.
 *
 * 8. Why the centre-of-pressure marker is transformed
 *
 *    OpenRocket measures centre of pressure forward-to-aft from the rocket tip.
 *    The imported rocket shares that origin and extends along world -Z, so the
 *    marker is placed by transforming the CP through the rocket's root coordinate
 *    system rather than assuming a world-space origin.
 *
 *    There is exactly ONE marker, on the first stage.  The condition that creates
 *    it is `i == 0 && parentInfo.isFirstTopComponent`, and the second half of
 *    that is the whole point:
 *
 *      - `depth == 1 && i == 0`, which is what it used to say, does NOT mean "the
 *        first stage".  `createComponents` recurses once per top-level component,
 *        so each stage opened its own level 1 and each one's first child matched.
 *        A two-stage rocket got two spheres -- one on the sustainer, one on the
 *        booster, the second one at the booster's tip, which is not a CP at all.
 *        CP is a property of the whole vehicle, so the second marker was simply
 *        wrong rather than a second reading of the same thing.
 *
 *      - `isFirstTopComponent` is a fact about the TREE, not about the level, so
 *        it has to be INHERITED rather than recomputed.  The write is
 *
 *            parentInfo.isFirstTopComponent == true || (depth == 0 && i == 0)
 *
 *        and the `||` is the whole trick.  The first attempt was the obvious
 *        `(depth == 0 && i == 0)`, and it removed the duplicate while deleting
 *        the marker altogether -- no centre of pressure anywhere on a two-stage
 *        rocket.
 *
 *        The reason is that this map is rebuilt at EVERY level, and each rebuild
 *        overwrites the field with its own answer.  At depth 1 the expression
 *        `(1 == 0 && ...)` is false for every entry, so the `true` that depth 0
 *        had just written was gone before the level-1 loop ever read it.  A
 *        correct value computed one level too late reads as a permanently false
 *        flag, and the symptom -- a marker that is simply absent -- looks like
 *        the condition is too strict rather than one frame out of date.
 *
 *        With the `||`, the flag is set once by the first component of the top
 *        level and every descendant inherits `true`; every other stage
 *        inherits `false` and stays false.  Note that a fix reading
 *        `parentInfo.isFirstTopComponent == true` ALONE would be wrong too: the
 *        top-level call is made with a hand-built `parentInfo` (see the feature
 *        body) that has no such field, so nothing would ever set it.
 *
 * 9. Why stacking advances by the bare `length`, shoulders included or not
 *
 *     `determineComponentLength` returns `params.length`, which for a nose cone
 *     or transition is the BARE cone length and excludes both shoulders, so a
 *     component with a shoulder overlaps whatever follows it.  That looks like a
 *     bug and is not; it is what OpenRocket does, confirmed in its source
 *     (branch `unstable`):
 *
 *       - `Transition` does NOT override `getLength()`, so it returns the bare
 *         `length` field, shoulders excluded.
 *       - `RocketComponent.getAxialOffset(...)` passes `parent.getLength()` as
 *         the `outerLength`, and `AxialMethod.AFTER` is `outerLength + offset`.
 *       - `Transition.getComponentBounds()` puts the fore shoulder at
 *         `x ∈ [-foreShoulderLength, 0]` and the aft at
 *         `[getLength(), getLength() + aftShoulderLength]`, i.e. the shoulder
 *         deliberately extends BEYOND the length it is stacked by.
 *
 *     `params.totalLength` is still published by the web app, and is the single
 *     place to switch if that ever stops being true.
 *
 * 10. Why the union result, not the base revolve, is returned
 *
 *     `createComponents` applies NAME, APPEARANCE and MATERIAL to whatever
 *     `completeComponent` returns.  When a component has a shoulder, the body
 *     that actually needs those properties is the merged one, so
 *     `unionShoulders` returns the UNION result and `completeComponent` passes
 *     that on.  Returning the original revolve would leave the shoulder an
 *     unnamed, uncoloured, unmaterialised body sitting in the part studio.
 *
 *     Two further details of the union are deliberate:
 *
 *       - `tools` is a Query (`qUnion([...])`), never a bare array.  An array
 *         there is a type error.
 *       - The base body comes FIRST in that array.  A UNION with no `targets`
 *         merges everything in `tools` and keeps the identity of the body that
 *         appears earliest, so putting the body first means the merged result
 *         inherits the component's identity rather than the shoulder's.
 *
 *     Each union is guarded: if it produces no body, the un-unioned body is kept
 *     and the shoulder is skipped, so a failed boolean costs a shoulder rather
 *     than the whole component.
 *
 * 11. Why the REVOLVE_FAILED println reports WHICH component, and what shape
 *
 *     A `REVOLVE_FAILED` notice names the line of the `opRevolve` call and
 *     nothing else.  That was not enough to diagnose anything: three theories
 *     about the cause were formed and disproved while the only visible symptom
 *     was "a revolve, somewhere, failed".
 *
 *     The failure-only println around that call names the component, its type,
 *     the FeatureScript's own error string, and a dump of its meridian section
 *     (point counts, `innerIsAxis`, which ends carry a shoulder, and the minimum
 *     outer and inner radius).  It prints nothing on success.  The point is to
 *     print the QUANTITY that distinguishes the candidate shapes rather than
 *     reason about which one it must be.
 *
 * 12. Why the failing component was a mass marker, not the nose cone
 *
 *     After the shoulder refactor, a REVOLVE_FAILED on `Bell X-1` still
 *     appeared -- and the stack trace is what identified it.  The trace was:
 *
 *         opRevolve (main.fs:516)
 *         completeComponent (main.fs:219)
 *         createComponents  (main.fs:214)   <- the RECURSIVE child call
 *         createComponents  (main.fs:92)    <- the top-level call, depth 0
 *
 *     `createComponents` is called at line 92 with `depth = 0`, and line 214 is
 *     the recursive call for a component's CHILDREN.  A top-level component's
 *     `completeComponent` is therefore reached WITHOUT passing through line 214.
 *     The trace passes through it, so the failing component is at depth >= 1: a
 *     child of a top-level component.
 *
 *     In `Bell X-1` that is a mass component inside a body tube -- "screw  eye
 *     (SE-1)", with `<packedlength>0.0</packedlength>` and a 12.5 mm radius.  The
 *     original report named the top-level nose cone, so the two were easy to
 *     conflate; they are unrelated failures.  See notes 12 in
 *     component_sketches.fs for the zero-length fix.
 *
 * 13. Why the `[revolve]` print is unconditional, and why it prints before the call
 *
 *     This supersedes the failure-only print described in note 11, which never
 *     fired.  It guarded on `getFeatureError(context, revolveId) != undefined`,
 *     and that check does not see a raw `@opRevolve` failure from here: the
 *     status API is meant to be consulted from inside a feature that WRAPS the
 *     failing call (std's own `boolean.fs` and `revolve.fs` use it that way, via
 *     `processSubfeatureStatus` on a subfeature), not by the caller immediately
 *     afterwards.  A guard that silently never fires is worse than no guard,
 *     because it looks like the code has already ruled the case out.
 *
 *     So the print is unconditional and BEFORE the call.  Unconditional because
 *     the discriminating fact is not "which one failed" but "which section shapes
 *     exist and which are axis-touching" -- the candidate set, not the verdict.
 *     Before the call because a notice for a failed feature is not guaranteed to
 *     be readable immediately after it either.
 *
 *     It prints the component name, its type, its `depth`, whether it was handed
 *     a face, and a dump of its section.  `[face]` does the same per sketch with
 *     the solved region count, and `[shoulder]` reports the new shoulder path,
 *     which is unproven in both directions because the body revolve has been
 *     failing before it is ever reached.
 *
 *     All three are TEMPORARY and should be removed once the failing component is
 *     identified.  They print on success as well as failure, which is the cost of
 *     not trusting a guard.
 *
 * 14. Why every revolve is wrapped in `try`/`catch`
 *
 *     A failed `opRevolve` THROWS, and an uncaught throw unwinds the whole
 *     remaining `createComponents` loop.  Everything after the first failure was
 *     therefore never built, never queried and never printed -- which is
 *     indistinguishable, in the log, from a truncated paste.  Two rounds were
 *     wasted concluding the log was cut off when it was in fact the run stopping
 *     dead at the first failure.
 *
 *     Catching it changes what can be observed: the rest of the rocket is built,
 *     so a log can be read as a whole rather than up to its first casualty.  The
 *     component itself is then left with no body, which the caller already
 *     handles -- it skips NAME, APPEARANCE, MATERIAL, the mate connectors and the
 *     composite part for a component that produced nothing.  The two steps that
 *     needed bodies are skipped explicitly (`revolveOk`): the shoulder union and
 *     the parachute/shock-cord fillet.
 *
 *     The failure is reported rather than swallowed silently: `[revolve] CAUGHT`
 *     names the component and prints the error, and `[revolve] DONE` states the
 *     resulting body count, so "threw" and "succeeded but produced no body" stay
 *     distinguishable.  A `[done] createComponents` line at the end of each level
 *     proves the run reached the end; if that line is missing, something outside
 *     a revolve threw.
 *
 * 15. Why a streamer is a canister, and why a tab needs the parent's sketches
 *
 *     Two components that look like they need their own branch, and do not.
 *
 *     A streamer is only modelled PACKED.  It is a `RecoveryDevice`, so it has a
 *     `packedLength` and a `packedRadius`, and its deployed form is a
 *     `stripLength` x `stripWidth` ribbon with no thickness anywhere in the file
 *     (its mass comes from the surface material's areal density).  So the
 *     canister section is drawn and the component revolves with every other
 *     recovery device.  Building the deployed ribbon instead would mean inventing
 *     a sheet thickness to extrude, and would put a sheet of plastic inside the
 *     rocket -- neither of which is what the packed part represents.
 *
 *     A fin tab does need its own branch, because its outer edge is the PARENT's
 *     surface rather than a straight line, and that surface only exists in the
 *     parent's sketch.  `completeComponent` therefore takes `parentSketch` and
 *     hands it to `unionFinTab`, which passes it to `sketchFinTab` -- the same
 *     reference `sketchComponent` already gets, and for the same reason: a fin's
 *     root is fitted against the parent, so the tab is fitted against the very
 *     curve the fin snapped to.  See component_sketches.fs note 22 for the shape
 *     itself and why it is a U with a projected outer edge rather than a
 *     rectangle.
 *
 *     Note what is NOT handed on: `parentSiblingSketches` goes to
 *     `sketchComponent` and stops there.  A fin root may overhang its parent and
 *     needs the siblings to close (notes 1, 3); a tab is clamped inside the root
 *     chord and never does.  More to the point, a tab is drawn from
 *     `completeComponent`, which runs after the first loop has solved EVERY
 *     sketch in the rocket, so by then the sibling fins are full of straight
 *     root chords that sit at the root radius and match the tab perfectly.  The
 *     tab would project one of those instead of the parent's profile.
 *
 *     The union happens BEFORE the cant and before the pattern, so an elliptical
 *     fin cants its tab along with itself and every angular instance carries its
 *     own tab.  And the UNION result is what carries on to the pattern and the
 *     naming path, never the bare fin (note 10).
 *
 * 16. Why a motor needs a feature parameter for its MASS but not for its length
 *     or its position
 *
 *     A motor is three dimensions, and they come from three different places --
 *     which is the whole answer to "does this need a parameter".
 *
 *     DIAMETER and LENGTH are in the file.  A `<motormount>` block carries an
 *     `<overhang>` and one `<motor>` per configuration, each with its own
 *     `<diameter>` and `<length>`; all six test rockets have one, so the size is
 *     never in doubt when a motor is selected at all.  No parameter.
 *
 *     POSITION is in the file too, and is OpenRocket's arithmetic rather than
 *     anything chosen here: `getMotorPosition()` returns
 *     `getLength() - motor.getLength() + getMotorOverhang()`, and `RocketRenderer`
 *     draws the motor at that same offset.  So the motor's fore end sits
 *     `mountLength - motorLength + overhang` aft of the mount's fore end, and a
 *     positive overhang pushes its aft end out past the mount's -- which is what
 *     an overhanging mount is.  The mount's own place in the rocket already comes
 *     from `position.axialMethod` / `axialOffset`.  Adding a parameter for this
 *     would only let a user contradict the design file, so there is none.
 *
 *     MASS is the one that is genuinely absent.  OpenRocket identifies a motor by
 *     `digest` against a thrust-curve database we do not ship, and looks the mass
 *     up there; nothing in the .ork records it.  So the mass has to come from the
 *     user, which is exactly what the pre-existing "Motor mass (g)" field was
 *     always for.  It was declared `isReal(..., POSITIVE_REAL_BOUNDS)` and then
 *     never read, so it forced everyone through a dialog box that did nothing --
 *     and those bounds made zero unenterable, so "no motor mass" was not even
 *     expressible.  It is now applied, via MASS_OVERRIDE: a motor is a bought-in
 *     part with a known mass, not something turned from the tube's material, and
 *     a material would also mean inventing elastic constants `resolveMaterial`
 *     has to invent anyway (main.fs note 2).
 *
 *     The parser now also carries the motor's `digest` through to
 *     `motorMount.digest`.  It is the key into that same thrust-curve database,
 *     so it is the one thing that would let a future build recover the mass
 *     without asking -- but recovering it still means shipping the database, and
 *     a digest with no matching entry is a motor we cannot weigh either way.  The
 *     field is in the JSON because it costs nothing and names the shortfall
 *     precisely; nothing below reads it yet.
 *
 *     `motorLength` is new, and is an OVERRIDE rather than a source, which is why
 *     it defaults to nothing.  It exists for the two cases the file cannot cover:
 *     a mount with no motor selected, which has a diameter and length of zero and
