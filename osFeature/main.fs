 * 17. Why `completeComponent` is given the PARENT's sketch, not the component's
 *
 *     `createComponents` runs two loops.  The first draws every component sketch
 *     at this level and is handed `parentInfo.parentSketch` -- the sketch of the
 *     level's PARENT -- which is correct, and is what `sketchComponent` uses.
 *
 *     The second loop then rebinds that same field to `componentSketches[i]`, the
 *     sketch of the component being finished, because that is what the component's
 *     CHILDREN need as their parent.  Its loop variable `parentInfo` shadows the
 *     function parameter, so by the time `completeComponent` is called, the field
 *     it reads holds the component's OWN sketch.
 *
 *     `completeComponent` wants the parent's, not the component's: a fin tab has
 *     to be snapped to the body it hangs off.  Reading the rebound field handed it
 *     the FIN'S OWN OUTLINE instead.  A regen showed the damage in the `[tab]`
 *     lines: 32 edges were offered, of which the winner was a 50 mm line at the
 *     root radius spanning exactly the fin's own root chord, and the rejects
 *     included rivals out at the fin's TIP radius -- edges a body tube does not
 *     have.  The tab took its top edge from the fin's own chord, and the parent's
 *     surface was never offered to it at all.
 *
 *     On a straight parent the two curves coincide, so this stayed invisible: the
 *     shape came out right by luck.  On a tapered or curved parent the tab's top
 *     edge would have been the fin's straight root chord rather than the surface
 *     note 22 requires, which is the whole reason the projection exists.
 *
 *     Fixed by capturing `parentOwnSketch` from the function parameter BEFORE the
 *     rebinding and passing that.  The rebinding is still correct and still
 *     needed -- it is only the read in `completeComponent` that was wrong.
 *
 * 18. Why `opPattern` is counted before it is called, and wrapped in try/catch
 *
 *     `opPattern` THROWS `CANNOT_RESOLVE_ENTITIES` when handed an empty entity
 *     set, and an uncaught throw aborts every component after it (note 14).  A
 *     regen of a two-stage rocket with fin-spike pods died exactly there:
 *
 *         [asm] Fin Spikes (bodytube) produced NO body
 *         [asm] Fin Spike Pod Set (podset) pattern produced no bodies
 *         @opPattern: CANNOT_RESOLVE_ENTITIES
 *
 *     The chain is worth spelling out, because the proximate cause is not the
 *     pattern.  A pod set has no body of its own, so `patternQuery` is its
 *     CHILDREN (note 3).  Its one child was a body tube with
 *     `thickness == outerRadius`, i.e. a solid rod, which `tubeWallSketch`
 *     refused to draw (component_sketches.fs note 26).  No child body, no
 *     pattern, throw.  Two independent defects that met: the missing solid is
 *     fixed there, and this guard is what stops the next one from truncating the
 *     build.
 *
 *     `canBeQuery(children)` was already guarding the union, and it was not
 *     enough: it is TRUE of an empty query.  Only a count distinguishes "no
 *     bodies" from "not a query", so that is what the guard uses.
 *
 * 19. Why the instance axis depends on what is being instanced
 *
 *     Note 5 says instances rotate about the rocket axis, and for a pod set that
 *     is exactly right -- `PodSet.getInstanceOffsets` returns
 *     (0, radius*cos, radius*sin), an orbit about the rocket axis, and a pod
 *     set's own transform is ALREADY offset radially by its radiusOffset, so
 *     its origin is not on that axis.  Rotating a pod set about its own axis
 *     would swing the second pod around the first instead of around the rocket.
 *
 *     A fin set is a different case.  Its instances are copies of a fin on a
 *     particular BODY, and they belong at equal angles around THAT body's axis.
 *     For a fin on the rocket's centreline the two axes coincide and the
 *     distinction is invisible -- which is why it survived so long.  For a fin
 *     on a pod's body tube they do not: the engine strakes' fins were patterned
 *     about the world Z_AXIS, which put all four fins of each strake in a ring
 *     around the ROCKET, at the pod's radius from the rocket axis rather than
 *     around the strake.
 *
 *     So the axis is chosen by kind: `Z_AXIS` for an assembly, and the line
 *     through the component's own mount point along its own direction --
 *     `line(tform.translation, tform.linear * (0, 0, 1))` -- for everything
 *     else.  On the centreline that line IS the world Z axis, so the common
 *     case is unchanged and the pod case becomes correct.
 *
 * 20. Why the mate connectors are created BEFORE the empty-body `continue`
 *
 *     A two-stage rocket needs a mate connector at the joint between the
 *     sustainer and the booster.  It had none, and the reason is an ordering
 *     mistake rather than a missing feature.
 *
 *     `isAssembly` covers pod sets and parallel stages but NOT `stage`, and a
 *     stage is a pure container: it has no sketch, so `completeComponent`
 *     revolves nothing for it and returns an empty query.  The second loop used
 *     to test that and `continue` immediately:
 *
 *         if (bodies == undefined || evaluateQueryCount(context, bodies) == 0)
 *         {
 *             ...
 *             continue;          <-- stage leaves here
 *         }
 *         ...
 *         if (depth <= 1)        <-- never reached for a stage
 *         {
 *             opMateConnector(... "topMateCoord" ...);
 *             opMateConnector(... "bottomMateCoord" ...);
 *         }
 *
 *     Every stage took the `continue`, so the `depth == 0` connectors -- the only
 *     ones that join one stage to the next -- were never created at all.  What
 *     did get created were the `depth == 1` ones between components WITHIN a
 *     stage, which is why the model looked half-wired: plenty of connectors,
 *     none of them at the stage separation.
 *
 *     The log said so plainly and was easy to misread:
 *
 *         [asm] Sustainer (stage) produced NO body (face=false, children=3)
 *
 *     For a stage that is CORRECT rather than a fault (note 3) -- and note 3
 *     already said so -- but here it was load-bearing, silently skipping the
 *     connector.  A message that is correct in one place and catastrophic in
 *     another is worth reading twice.
 *
 *     Two changes follow from moving the connectors above the `continue`:
 *
 *       - The OWNER falls back to the children.  A stage has no body to own a
 *         connector, and its children are precisely what has to mate to the next
 *         stage, so `mateOwner` becomes the children query when `bodies` is
 *         empty.  The fallback keys off an evaluated COUNT, not `canBeQuery`,
 *         for the reason in note 18: `canBeQuery` is true of an empty query and
 *         would hand `opMateConnector` an empty owner.
 *
 *       - The `i != 0` / `i != last` tests are unchanged, and still do the job
 *         they were written for.  A single-stage rocket has `numComponents == 1`
 *         at depth 0, so neither fires and it grows no connector at either end
 *         that has nothing to mate to; a two-stage rocket gets an aft connector
 *         on the first stage and a fore connector on the second, which is the
 *         one joint that exists.  The condition is `numComponents`, not a stage
 *         count, and that is correct: a pod set occupying the same level is a
 *         component like any other and is mated to its neighbour the same way.
 *
 *     `lastPosition` is the stage's aft end because the web app sets an
 *     assembly's `params.length` to the sum of its `after`-positioned children
 *     (geometry.ts), which is what `resolveTransform` then advances by.
 *
 * 21. Why `readMotorOptions` passes the two overrides as different kinds of value
 *
 *     The feature's parameters become one map that the rest of the file carries
 *     around, and the two entries are deliberately not the same kind of thing.
 *
 *       - `massGrams` comes from `isReal`, so it is a DIMENSIONLESS number.  The
 *         grams are named in the field and nowhere else.
 *       - `overrideLength` comes from `isLength`, so it is already a LENGTH
 *         carrying its unit, and is passed on as one.  Converting it to a bare
 *         number here would mean hard-coding a unit and re-introducing exactly
 *         the bug a units-aware field exists to prevent.
 *
 *     Both default to 0 by their bounds, and the callers read 0 as "not supplied"
 *     (note 16).  The `undefined` fallbacks are belt and braces: they cost
 *     nothing and mean a definition that somehow lacks the field still behaves.
 *
 *     The zero comparison follows from the same distinction.  A zero length is a
 *     LENGTH and is compared against `0 * meter`; a zero mass is a bare number
 *     and is compared against `0`.  Mixing those up is a compile-time type error
 *     rather than a silent zero, which is the good failure mode -- but it is an
 *     error nonetheless, and the two are easy to confuse because they read alike.
 *
 * 22. Why the motor mass bounds are written out rather than named
 *
 *     The range is 0 .. 1000 g and the DEFAULT is 0.  The default is the part
 *     that matters, and it is why this is a literal `RealBoundSpec` instead of
 *     `POSITIVE_REAL_BOUNDS`:
 *
 *       - `POSITIVE_REAL_BOUNDS` does allow 0, but it DEFAULTS TO 1.  Every
 *         motor the user did not think about would silently gain a gram, and
 *         nothing in the log would say so.
 *       - 0 is the one value `applyMotorMass` reads as "not supplied", and it
 *         prints a line saying the mass was left unset.  That is what makes blank
 *         mean blank rather than mean one gram.
 *
 *     The upper bound of 1000 g is a sanity limit, not a design decision: it
 *     exists so a typo cannot be accepted as a motor the size of the rocket.
 *
 * 23. How to read the `[tab]` pair of lines against each other
 *
 *     `sketchFinTab` prints `asked for:` before solving; `reportTabSketchCurves`
 *     prints what the SOLVED sketch actually holds.  Read the two together,
 *     because the failure modes they separate are otherwise indistinguishable:
 *
 *       - `tabSurface` comes back spanning only the tab's own span, so the
 *         PROJECTION is the bug -- the parent surface never reached the sketch.
 *       - `tabSurface` spans the parent and the region is still short, so the
 *         REGION SOLVER is the bug.
 *
 *     Four rounds of guessing could not tell those apart, because both present
 *     as the same "faces=0".  One `[tab] ... solved sketch holds N curve(s)`
 *     line settles it, which is the whole reason that dump exists and why it is
 *     worth its length in the log.
 *
 * 24. Why the two motor fields are declared conditionally, and how
 *
 *     Both exist only to FILL A GAP the file leaves, and the gap is not always
 *     there.  A motor's diameter and length come from the `<motor>` block, and on
 *     all six test rockets they are there; a designer then has nothing to type,
 *     and a dialog field that cannot change the result is worse than no field,
 *     because it invites the belief that it did.  So each field is declared only
 *     when the payload does not already carry what it would override, and the two
 *     are gated SEPARATELY -- a file with a length but no mass must keep the mass
 *     field, which a single shared flag would have thrown away with the length
 *     one.
 *
 *     The mechanism is forced, and not in an obvious way.  A precondition is
 *     ANALYSED, never executed: Onshape builds the dialog from a static read of
 *     the declaration, so the first attempt -- compute a local, then `if` on it --
 *     is not merely unidiomatic but illegal.  A `var` in a precondition is
 *     "Unexpected statement type (variable declaration)", and an `if` whose
 *     condition is not built from parameter ids is "Could not identify parameter
 *     id in either operand of comparison", which together fail the whole
 *     precondition with "precondition analysis failed" and the feature does not
 *     appear in Part Studios at all.  It fails LOUDLY, which is worth something:
 *     a feature that cannot be placed is noticed immediately, unlike a motor
 *     quietly wearing the wrong name.
 *
 *     So the answer has to travel as a PARAMETER.  `motorMassInFile` and
 *     `motorLengthInFile` are declared `is boolean` in the precondition -- the
 *     type is `boolean`, and `bool` is not a FeatureScript type at all -- and the
 *     two `if` statements test nothing else.  `oroEditingLogic`, named in the
 *     "Editing Logic Function" annotation, is what reads the JSON and sets those
 *     two flags.  Onshape calls it whenever the definition changes, so attaching
 *     a different file recomputes them: the fields follow the payload instead of
 *     whatever happened to be true when the feature was first dropped.  Doing the
 *     read in the body instead was the other option, and it cannot work -- by the
 *     time the body runs, the dialog has already been built with every field
 *     shown.
 *
 *     Both flags carry `UIHint.ALWAYS_HIDDEN`, which is what makes this honest.
 *     Neither is an INPUT: each exists only to carry the payload's answer into an
 *     `if`, and a visible checkbox would be a control the user is invited to
 *     operate, on a question the file has already answered.  Ticking it would
 *     hide a field that still has something to say, and the feature would then
 *     disagree with the JSON while looking deliberate.  Hidden, the conditional
 *     reads as a fact about the payload -- "this file has the length, so there is
 *     nothing to override" -- rather than as a switch.
 *
 *     The "Name" annotations on the hidden flags are therefore documentation for
 *     whoever opens the file, not labels anyone sees, which is why they say what
 *     the flag MEANS ("Motor mass in file") and not what it does.
 *
 *     The condition is "does the payload have it", never "the file never has it".
 *     That distinction is the whole reason mass still works.  OpenRocket resolves
 *     motor mass from a thrust-curve database this importer does not ship, so
 *     nothing in the .ork records it and `MotorMountParams` has no `mass` key at
 *     all (note 16).  Written as a lookup, `jsonHasMotorMass` is false for every
 *     file today, the field is always offered, and it disappears by itself the day
 *     a parser starts emitting one.  Written as the constant `false` it would
 *     behave identically today and then silently start overriding a mass the file
 *     had supplied -- a bug that could only appear after a change to a different
 *     file, which is the hardest kind to find.
 *
 *     The lookup walks `comp.children` as well as the components it is given.  A
 *     booster stage is several levels down and its motor is a real motor; testing
 *     only the top level would call a two-stage rocket "has no motor" and offer a
 *     length override for a motor the file already sized.
 *
 *     And the no-JSON-yet case reports "not in file", showing both fields.  A
 *     brand new feature has no payload to inspect, so "not found in the JSON"
 *     would be trivially true and the fields would never appear -- on the one
 *     feature where the user is about to attach the file and would expect them.
 *     Nothing is lost either way: `readMotorOptions` reads an undeclared parameter
 *     as 0, which is already what an untouched field means, so a hidden field and
 *     a blank one are the same value to everything downstream.
 *
 * 25. Why a level's result carries its children's bodies as well as its own
 *
 *     `createComponents` hands its caller a query, and the caller uses it for
 *     two things: the assembly's mate owner, and the composite part that wraps a
 *     stage's geometry.  Both want EVERYTHING below the level, but the value
 *     used to be only what that level drew for itself.
 *
 *     The reason is that `componentQueryArray` collected `bodies`, and `bodies`
 *     is what `completeComponent` returned -- which, for anything that is not an
 *     assembly, is the component's OWN geometry and nothing else (note 3).  A
 *     child is not in its parent's `bodies`; a child is in the parent's
 *     `childrenQuery`, and only there.  So the query that came back up each
 *     level described that level's direct children and stopped, and the recursion
 *     lost a generation on the way up.
 *
 *     It shows up wherever a component is a wrapper for geometry of its own
 *     rather than a leaf, which in an .ork file is exactly the tube coupler: it
 *     hangs off a body tube, and its own children -- the centering rings and
 *     bulkheads a designer drops inside it -- sat one level below the query the
 *     body tube returned.  The coupler itself appeared in the composite part
 *     because it was a direct child, and its contents did not, so the composite
 *     looked complete at a glance and was hollow underneath.  A three-deep tree
 *     under a stage is the only shape that loses anything, which is why the
 *     shallower cases (a fin's tab, an inner tube's motor mount) never showed it
 *     either way.
 *
 *     The fix is to append `childrenQuery` alongside `bodies` rather than instead
 *     of it, and both guards are load-bearing.  An assembly is skipped because it
 *     already returned its children: `bodies` for a single-instance assembly IS
 *     `children`, so adding the query again would list every one of its children
 *     twice in the composite part, which Onshape rejects rather than quietly
 *     deduplicating.  And the count is re-read at the point of the append rather
 *     than reused from the `childrenQuery` evaluation further up, because
 *     opPattern CONSUMES the bodies it patterns (note 3): a fin's tab and an
 *     instanced component's children are gone by then, and a count taken before
 *     the pattern would queue a query of deleted bodies into the composite part.
 *     Read after, a consumed set evaluates to zero and is skipped by the same
 *     test that already covers the empty case.
 *     test that already covers the empty case.
 *
 * 26. Why the editing logic, and not the precondition, reads the JSON
 *
 *     A precondition is ANALYSED, never executed, so its `if` statements may only
 *     test a parameter id (note 24).  Nothing derived from the attached file can
 *     be computed there.  The answer therefore has to travel in the definition as
 *     a parameter, and `oroEditingLogic` is what carries it.
 *
 *     It re-runs on every change, which is the whole point: attach a different
 *     payload and the two "in file" flags are recomputed, so the motor-mass and
 *     motor-length fields appear and disappear with the file rather than with
 *     whatever happened to be true when the feature was first dropped into the
 *     document.
 *
 * 27. Why `jsonHasMotorMass` is a lookup and not a `false`
 *
 *     Nothing writes `motorMount.mass` today, because OpenRocket recovers a
 *     motor's mass by digest lookup in a thrust-curve database the importer does
 *     not ship (note 16).  So the answer is false for every real file and the
 *     mass field is always offered.
 *
 *     It is written as a search rather than a hard `false` so that the field
 *     removes ITSELF if a future parser starts emitting the key.  Hard-coding
 *     `false` would keep overriding a mass the file did supply, which is the
 *     failure mode worth avoiding: a silently ignored value is worse than a
 *     missing one.
 *
 * 28. Why the motor's name and colour are applied twice
 *
 *     The mount's NAME, APPEARANCE and MATERIAL are set on every body the mount
 *     produced, and that includes the motor, which therefore inherits the
 *     mount's identity.  `styleMotor` is the corrective: it takes the motor body
 *     directly while the query is still in hand, rather than searching for it
 *     later, and is called from inside `addMotor`.
 *
 *     `restyleMotor` then re-applies it after the mount's properties have
 *     landed.  This is belt and braces, and the second call is the one that wins:
 *     if anything renames the motor in between, only a call that runs last
 *     corrects it.  It does have to find the motor by the id `addMotor` revolved
 *     it under, which is why the DEBUG line reporting that count matters -- an
 *     empty count is a motor left wearing the mount's name, and it is the only
 *     way to tell that apart from a motor that was never created at all.
 *
 * 29. What the cant transform is, and why it is the same for every fin type
 *
 *     Cant rolls the finished solid about the fin's span axis, through the
 *     mid-point of its root chord.  That is exactly what OpenRocket does:
 *     `FinSet.getInstanceOffsets()` applies `getCantRotation()` between
 *     `translate(length / 2, 0, 0)` and `translate(-length / 2, 0, 0)`, and
 *     `getCantRotation()` is a rotation about the SPAN.  The span, not the chord,
 *     is the axis: it is what tilts the fin's faces and so produces roll.
 *
 *     It is applied to the solid rather than to the sketch, and after the tab
 *     union, so the tab cants along with the fin instead of fighting it (note 15).
 *
 *     All three planar fin types are sketched on the same plane
 *     (`tform * FRONT_SKETCH_PLANE`) and share one profile convention -- the
 *     sketch's x is the span, its y the chord -- so the axis and the pivot are
 *     the same expression for all of them.  The branches differ only in the
 *     direction each type is EXTRUDED along, and an extrusion direction is a
 *     property of the solid, not of the axis it is later rolled about.  That is
 *     why one helper serves all three rather than one per type.
 *
 *     Two details the helper settles.  The pivot is half the ROOT chord, taken
 *     through `finRootChord`, because a freeform fin has no `rootChord` and the
 *     geometry pass supplies the same extent as `length`; reading `rootChord`
 *     directly yields NaN there.  And a zero cant returns early rather than
 *     issuing a rotation by zero, which is a pointless feature on every fin in
 *     the common case where the designer set no cant at all.
 *
 * 30. Which components reach the radius-offset branches, and why
 *
 *     `parentRadius` is derived by the web app, not computed here, and it is set
 *     only for components whose placement is driven by `position.radiusOffset`.
 *     The surface-mounted parts -- fin sets, tube fins, launch lugs, rail buttons
 *     -- are excluded, because each of them places itself through
 *     `params.offsetRadius`, which is already folded into the sketch or the
 *     revolve origin.  Adding the parent's radius on top of that would displace
 *     them by it a second time.
 *
 *     This is not a theoretical hazard.  `radiusoffset method="surface"` is the
 *     single most common encoding in real files, and a census of OpenRocket's 17
 *     bundled designs plus this project's 7 shows all 61 of its uses are on fin
 *     sets, every one with a stored value of 0.0.  Treating `surface` as a plain
 *     alias for `relative` would therefore have thrown every fin in the corpus
 *     clear off the rocket.  The web app is where that distinction is enforced;
 *     here it is only honoured.
 *
 * 31. `angleMethod`: what RELATIVE does and why FIXED is an empty branch
 *
 *     `AngleMethod.RELATIVE.getAngle()` returns the parent's angle offset PLUS
 *     the requested one.  `newTransform` already carries the parent's angle,
 *     inherited through the chain, so RELATIVE is an extra rotation about the
 *     axis and nothing more.
 *
 *     `AngleMethod.FIXED.getAngle()` returns 0.00 -- not the stored offset, not
 *     an absolute angle: the component keeps its parent's angle and the offset in
 *     the file is IGNORED.  So the FIXED case is the absence of a rotation, which
 *     is what falling through the RELATIVE branch already did.  It is spelled out
 *     as an empty branch anyway, so that it reads as the decision it is rather
 *     than as an oversight, and so that a value the parser did not recognise
 *     cannot land here by accident and be mistaken for a handled case.  The
 *     parser warns on any method it does not honour and falls back to `relative`.
 *
 * 32. What `radiusoffset method="surface"` means, and why the stored value is
 *     not added
 *
 *     `RadiusMethod.SURFACE.getRadius()` returns the parent's outer radius plus
 *     the component's own bounding radius, and never touches the requested
 *     offset; `getAsOffset` returns 0.  SURFACE is therefore RELATIVE with a
 *     zero offset: it means "on the parent's surface", not "this far off it".
 *
 *     The web app's `parentRadius` already describes that placement -- the
 *     parent's surface radius at this component's own axial station, plus the
 *     assembly's bounding radius where one applies -- so the transform adds
 *     `parentRadius` and nothing else.
 *
 *     A reading that added the stored offset as well would be defensible against
 *     the prose, and the two agree on every real design because all 61 stored
 *     values are 0.0.  Upstream's reading is the one taken, because it is the
 *     one OpenRocket itself renders with.
 *
 * 33. Which components instance along the axis rather than round it
 *
 *     `LineInstanceable` types repeat themselves along the body's own axis,
 *     stepping aft by `<instanceseparation>`, instead of being patterned around
 *     it.  The set is fixed by the Java class hierarchy:
 *
 *     - `LaunchLug`           implements LineInstanceable
 *     - `RailButton`          implements LineInstanceable
 *     - `RadiusRingComponent` implements LineInstanceable
 *       - `Bulkhead`             extends RadiusRingComponent
 *       - `CenteringRing`        extends RadiusRingComponent
 *
 *     `InnerTube`, `TubeCoupler` and `EngineBlock` are NOT in this set.  They
 *     extend `ThicknessRingComponent`, which is a SIBLING of
 *     `RadiusRingComponent` under `RingComponent` and does not implement
 *     `LineInstanceable`.  Treating them as line-instanceable would stack a
 *     multi-tube motor mount into one long tube down the middle of the rocket.
 *
 *     The whole rule lives in `isLineInstanceable` so it cannot drift out of
 *     step with the upstream type list, and so that a type added here later has
 *     to be argued for against the hierarchy rather than matched by name
 *     inline at the call site.
 *
 * 34. Why a PATTERNED assembly hands up its ORIGINAL children as well
 *
 *     A pod set's first instance was missing from its parent's composite part,
 *     and only its first: every copy was there.  The whole chain is in what a
 *     level hands back to its caller, and nothing about the geometry is wrong.
 *
 *     `completeComponent` returns, for an assembly, only the bodies `opPattern`
 *     CREATED (note 3).  That is deliberate rather than an oversight -- the
 *     caller applies NAME and APPEARANCE to whatever comes back, and a pod's
 *     children have to keep their own names, which is what the `!isAssembly`
 *     guard on the property block is for.  The originals are therefore absent
 *     from `bodies` BY DESIGN, and something else has to supply them.
 *
 *     Two candidates existed, and both are wrong:
 *
 *       - The `childrenQuery` re-read, which is what a non-assembly uses.  It
 *         is skipped for assemblies, correctly, because `bodies` for an assembly
 *         already IS its children and adding the query again would list each
 *         child twice in the composite part, which Onshape rejects (note 25).
 *         For a PATTERNED assembly it would have been wrong twice over: the
 *         pattern consumed those bodies, so the re-read evaluates to zero.
 *
 *       - `qCreatedBy(patternId, EntityType.BODY)`, which is the copies again --
 *         the thing that was already working, and the reason only the original
 *         went missing.
 *
 *     What is left is the array `children`, evaluated at the top of the second
 *     loop, BEFORE `completeComponent` ran and so before the pattern consumed
 *     anything.  A held array of entity references stays valid across the
 *     pattern: `opPattern` re-parents its source bodies under the new feature
 *     rather than deleting them, which is why std deletes its pattern seeds
 *     with an explicit `opDeleteBodies` afterwards (`sheetMetalPattern.fs`,
 *     `patternSeeds`) -- they are still there and have to be removed on purpose.
 *     So the pre-pattern array is the only handle on the original instance, and
 *     appending it is what puts the first pod into the composite part.
 *
 *     The `instanceCount > 1` test is what separates the two assembly cases,
 *     and it is load-bearing for the duplicate reason given above:
 *
 *       - A single-instance assembly never reaches the pattern branch, so its
 *         `bodies` IS its children and appending them again would double them.
 *       - A patterned assembly's `bodies` are the COPIES, a set disjoint from
 *         the originals, so the union is exactly `instanceCount` instances.
 *
 *     Only the composite part was visibly affected, and only for a pod set
 *     nested BELOW depth 1.  At depth 1 the composite is built directly from the
 *     pre-pattern `children` array and so always had the original; deeper, that
 *     array first has to survive the trip up through `componentQueryArray`, and
 *     that is the step that dropped it.
 *
 *     THE TRAP, and why the original does not simply go into the return value: a
 *     level's return is not only "everything under this node".  It is handed
 *     straight back to the parent as `children`, and `completeComponent` uses
 *     that as its PATTERN SOURCE (`patternQuery`) whenever the parent itself
 *     instances.  An original appended there is instanced a SECOND time by an
 *     enclosing pod set, and the pods move.  The first attempt at this fix did
 *     exactly that and a regen showed the pods displaced.
 *
 *     So the original travels in a second channel instead.  `assemblyOriginals`
 *     is a FRESH array per component, put in the child's `parentInfo`, which the
 *     recursion fills and the parent's composite part reads.  Two properties make
 *     it safe, and both are the reason it is a separate array rather than a
 *     shared one:
 *
 *       - It is never a pattern source.  `componentQueryArray` -- the only value
 *         that reaches `patternQuery` -- is left exactly as it was.
 *       - It is per SUBTREE, so a sibling pod's originals cannot land in this
 *         component's composite part, and no body is listed twice, which Onshape
 *         rejects (note 25).
 *
 *     The composite part therefore takes `children`, the component's own `bodies`
 *     and the collected originals, which for a two-instance pod set is both
 *     instances whatever the nesting.
